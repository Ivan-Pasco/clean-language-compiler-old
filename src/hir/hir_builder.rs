//! HIR Builder - converts AST to HIR (High-level Intermediate Representation)
//!
//! This module implements the transformation from AST to HIR, which includes:
//! - Desugaring syntactic constructs into normalized forms
//! - Validating semantic consistency (but not type checking)
//! - Converting implicit operations to explicit ones
//! - Maintaining source location information for error reporting

use crate::ast::SourceLocation;
use crate::ast::{
    AssignmentTarget, BinaryOperator, Class, Constructor, Expression, Function, ListBehavior,
    Parameter, Program, ResetTarget, Statement, StringPart, Type, UnaryOperator,
    ValidateConstraint, Value,
};
use crate::error::CompilerError;
use crate::hir::*;

/// Registry entry for a callable's parameter list, used for named-argument resolution
/// (FUNC008–FUNC011 per foundation/spec/semantic-rules.md).
#[derive(Debug, Clone)]
struct CallableSignature {
    /// Ordered list of parameter names exactly as declared.
    param_names: Vec<String>,
}

/// Accumulator analysis result — populated by walking a loop body to decide
/// whether the string-accumulator-loop rewrite is safe to apply.
#[derive(Debug, Default)]
struct AccumulatorAnalysis {
    /// Number of canonical self-appends (`acc = acc + …`) seen.
    self_appends: u32,
    /// Number of reads of `acc` outside the canonical self-append's LHS slot.
    reads: u32,
    /// Set to true if any disqualifier is observed (early return,
    /// suspension point, prepend, write to `acc` from a non-canonical
    /// site, etc.). Short-circuits the walk.
    disqualified: bool,
}

impl AccumulatorAnalysis {
    fn is_rewritable(&self) -> bool {
        !self.disqualified && self.self_appends == 1 && self.reads == 0
    }
}

/// Result of a successful accumulator-pattern match. Constructed by
/// `try_match_accumulator_pair` and consumed by
/// `rewrite_string_accumulator_loops` to splice the rewrite into the
/// caller's statement vector.
struct AccumulatorRewrite {
    /// Replaces the original `string acc = ""` decl with the builder init.
    decl_replacement: HirStatement,
    /// Captures HEAP_PTR right after the builder is constructed. Inserted
    /// between `decl_replacement` and the loop ONLY when a paired
    /// per-iter `string_builder_reclaim` call is also emitted into the
    /// body. The two are emitted together — emitting the mark without
    /// a consumer just wastes an integer local. `None` means the
    /// rewrite skipped reclaim emission (because escape analysis flagged
    /// the body) and the mark is not needed.
    mark_decl: Option<HirStatement>,
    /// Replaces the original `while`/`for` with the same loop whose body
    /// has the self-append rewritten to `string_builder_append` and
    /// whose tail emits `string_builder_reclaim(__sb, __mark)`.
    replacement_loop: HirStatement,
    /// Inserted immediately after the loop: rebinds `acc` to the
    /// finalized string so any downstream reader sees a normal string.
    finalize_decl: HirStatement,
}

/// Internal marker used during accumulator-pattern detection to remember
/// which kind of loop we matched (so we reconstruct the same variant
/// after rewriting the body).
enum LoopKind {
    While,
    For,
}

/// HIR Builder - constructs HIR from AST
pub struct HirBuilder {
    type_inference_counter: usize,
    warnings: Vec<CompilerError>,
    constant_bindings: std::collections::HashSet<String>,
    /// Nesting depth: 0 = top-level, >0 = inside a function/block.
    /// Used to enforce that apply blocks and import statements may only
    /// appear at the top level of a program.
    scope_depth: usize,
    /// Registry of callable signatures populated during the pre-scan pass.
    /// Keys are function names (for free functions) or `ClassName` (for constructors)
    /// or `ClassName::method` (for methods).
    named_arg_registry: std::collections::HashMap<String, CallableSignature>,
    /// Continuation functions generated by the `later + api.*` CPS transform.
    /// Appended to the module's function list after the main HIR pass.
    pending_functions: Vec<crate::hir::HirFunction>,
    /// Counter for generating unique continuation names.
    later_counter: usize,
    /// Name of the function currently being built (for naming continuations).
    current_function_name: String,
    /// Maps local variable names declared via `later varName = api.*` to their
    /// API namespace (e.g. "result" → "api"). Used by `build_expression` to
    /// substitute `result.ok` → `api.ok()`, `result.json(p)` → `api.json(p)`, etc.
    api_response_vars: std::collections::HashMap<String, String>,
    /// Initial values of top-level state variables, keyed by name. Pre-scanned in
    /// `build_hir` before functions are lowered so `reset <name>` statements can
    /// expand inline to `<name> = <initializer>` without depending on a host
    /// bridge to remember the original value.
    state_initializers: std::collections::HashMap<String, crate::ast::Expression>,
    /// Monotonic counter used to name temporaries introduced by the
    /// string-accumulator-loop rewrite that resolves
    /// CMP-SSR-MALLOC-OOM-PAGE-RENDER. Each rewritten loop gets a unique
    /// `__sb_N` local. Mirrors `later_counter` — never reset, so a single
    /// build never produces colliding names.
    string_builder_counter: usize,
}

impl HirBuilder {
    /// Create a new HIR builder
    pub fn new() -> Self {
        // named_arg_registry is populated lazily via prescan_signatures()

        Self {
            type_inference_counter: 0,
            warnings: Vec::new(),
            constant_bindings: std::collections::HashSet::new(),
            scope_depth: 0,
            named_arg_registry: std::collections::HashMap::new(),
            pending_functions: Vec::new(),
            later_counter: 0,
            current_function_name: String::new(),
            api_response_vars: std::collections::HashMap::new(),
            state_initializers: std::collections::HashMap::new(),
            string_builder_counter: 0,
        }
    }

    // =========================================================================
    // later + api.* CPS helpers
    // =========================================================================

    /// Map `result.{prop}` → bridge method name for the given namespace.
    /// Properties are zero-arg bridge calls.
    fn api_response_property_to_bridge(namespace: &str, prop: &str) -> Option<String> {
        match namespace {
            "api" => match prop {
                "ok" => Some("ok".to_string()),
                "status" => Some("status".to_string()),
                "body" => Some("body".to_string()),
                _ => None,
            },
            _ => None,
        }
    }

    /// Map `result.{method}(args)` → bridge method name for the given namespace.
    /// Returns the renamed method or None if not a known response accessor.
    fn api_response_method_to_bridge(namespace: &str, method: &str) -> Option<String> {
        match namespace {
            "api" => match method {
                "json" => Some("json".to_string()),
                "header" => Some("responseHeader".to_string()),
                _ => None,
            },
            _ => None,
        }
    }

    // =========================================================================
    // Named-argument resolution (FUNC008–FUNC011)
    // =========================================================================

    /// Pre-scan phase: walk the raw AST `Program` and populate `named_arg_registry`
    /// with all user-defined function signatures, constructor signatures, and method
    /// signatures.  This must be called before `build_hir` processes any expressions.
    fn prescan_signatures(&mut self, program: &Program) {
        // Free functions from program.functions
        for func in &program.functions {
            self.register_function_signature(&func.name, &func.parameters);
        }

        // start function
        if let Some(start) = &program.start_function {
            self.register_function_signature("start", &start.parameters);
        }

        // Functions from top-level FunctionsBlock statements
        for stmt in &program.statements {
            if let Statement::FunctionsBlock {
                functions: func_list,
                ..
            } = stmt
            {
                for func in func_list {
                    self.register_function_signature(&func.name, &func.parameters);
                }
            }
        }

        // Classes from program.classes
        for class in &program.classes {
            self.register_class_signatures(class);
        }

        // Classes from ClassDefinition statements
        for stmt in &program.statements {
            if let Statement::ClassDefinition { class, .. } = stmt {
                self.register_class_signatures(class);
            }
        }
    }

    /// Register a free function's parameter list under its name.
    fn register_function_signature(&mut self, name: &str, params: &[Parameter]) {
        let sig = CallableSignature {
            param_names: params.iter().map(|p| p.name.clone()).collect(),
        };
        self.named_arg_registry.insert(name.to_string(), sig);
    }

    /// Register a class constructor and all method signatures.
    fn register_class_signatures(&mut self, class: &Class) {
        // Constructor is registered under the class name itself.
        if let Some(ctor) = &class.constructor {
            let sig = CallableSignature {
                param_names: ctor.parameters.iter().map(|p| p.name.clone()).collect(),
            };
            self.named_arg_registry.insert(class.name.clone(), sig);
        }

        // Each method is registered under `ClassName::methodName`.
        for method in &class.methods {
            let key = format!("{}::{}", class.name, method.name);
            let sig = CallableSignature {
                param_names: method.parameters.iter().map(|p| p.name.clone()).collect(),
            };
            self.named_arg_registry.insert(key, sig);
        }
    }

    /// Check whether `args` contains any `NamedArgBinding` expressions.
    fn has_named_args(args: &[Expression]) -> bool {
        args.iter()
            .any(|a| matches!(a, Expression::NamedArgBinding { .. }))
    }

    /// Resolve a mix of positional and named arguments into canonical positional
    /// order, enforcing FUNC008–FUNC011.
    ///
    /// # Arguments
    /// * `callee` — human-readable name of the callee for error messages
    /// * `sig`    — ordered parameter names of the callee
    /// * `args`   — raw argument list from the AST (may contain NamedArgBinding nodes)
    /// * `location` — source location for error reporting
    fn resolve_named_args<'a>(
        callee: &str,
        sig: &CallableSignature,
        args: &'a [Expression],
        location: &SourceLocation,
    ) -> Result<Vec<&'a Expression>, CompilerError> {
        let param_count = sig.param_names.len();
        let arg_count = args.len();

        // FUNC011: argument count must match parameter count.
        if arg_count != param_count {
            return Err(CompilerError::semantic_error_with_code(
                format!(
                    "FUNC011: `{}` expects {} argument(s), got {}",
                    callee, param_count, arg_count
                ),
                Some(format!(
                    "Provide exactly {} argument(s): {}",
                    param_count,
                    sig.param_names.join(", ")
                )),
                Some(location.clone()),
                "FUNC011",
            ));
        }

        // Split into positional prefix and named args.
        let mut last_positional_idx: Option<usize> = None;
        let mut first_named_idx: Option<usize> = None;
        for (i, arg) in args.iter().enumerate() {
            if matches!(arg, Expression::NamedArgBinding { .. }) {
                if first_named_idx.is_none() {
                    first_named_idx = Some(i);
                }
            } else {
                // Positional argument.
                // FUNC010: positional args must precede all named args.
                if let Some(named_start) = first_named_idx {
                    return Err(CompilerError::semantic_error_with_code(
                        format!(
                            "FUNC010: positional argument at position {} appears after named \
                             argument at position {} in call to `{}`",
                            i, named_start, callee
                        ),
                        Some(
                            "All positional arguments must come before named arguments".to_string(),
                        ),
                        Some(location.clone()),
                        "FUNC010",
                    ));
                }
                last_positional_idx = Some(i);
            }
        }

        // Number of leading positional arguments.
        let positional_count = last_positional_idx.map(|i| i + 1).unwrap_or(0);

        // Build output slot array: None means "not yet filled".
        let mut slots: Vec<Option<&Expression>> = vec![None; param_count];

        // Fill positional slots first.
        for (i, arg) in args[..positional_count].iter().enumerate() {
            slots[i] = Some(arg);
        }

        // Fill named slots.
        // FUNC009: duplicate label detection via a simple scan.
        let mut seen_labels: Vec<&str> = Vec::new();
        for arg in args[positional_count..].iter() {
            if let Expression::NamedArgBinding {
                label,
                value: _,
                location: arg_loc,
            } = arg
            {
                // FUNC009: no duplicate labels.
                if seen_labels.contains(&label.as_str()) {
                    return Err(CompilerError::semantic_error_with_code(
                        format!(
                            "FUNC009: duplicate named argument `{}` in call to `{}`",
                            label, callee
                        ),
                        Some(format!("Remove the duplicate `{}:` argument", label)),
                        Some(arg_loc.clone()),
                        "FUNC009",
                    ));
                }
                seen_labels.push(label.as_str());

                // FUNC008: label must match a declared parameter name.
                let param_idx = sig.param_names.iter().position(|n| n == label);
                match param_idx {
                    None => {
                        return Err(CompilerError::semantic_error_with_code(
                            format!(
                                "FUNC008: `{}` has no parameter named `{}` in call to `{}`",
                                callee, label, callee
                            ),
                            Some(format!(
                                "Valid parameter names are: {}",
                                sig.param_names.join(", ")
                            )),
                            Some(arg_loc.clone()),
                            "FUNC008",
                        ));
                    }
                    Some(idx) => {
                        if idx < positional_count {
                            return Err(CompilerError::semantic_error_with_code(
                                format!(
                                    "FUNC011: parameter `{}` (position {}) is already covered \
                                     by a positional argument in call to `{}`",
                                    label, idx, callee
                                ),
                                Some(format!(
                                    "Remove the positional argument or the `{}:` label",
                                    label
                                )),
                                Some(arg_loc.clone()),
                                "FUNC011",
                            ));
                        }
                        slots[idx] = Some(arg);
                    }
                }
            }
        }

        // Verify all slots are filled (FUNC011 complete coverage).
        let mut result = Vec::with_capacity(param_count);
        for (i, slot) in slots.iter().enumerate() {
            match slot {
                Some(expr) => result.push(*expr),
                None => {
                    return Err(CompilerError::semantic_error_with_code(
                        format!(
                            "FUNC011: parameter `{}` (position {}) is not covered in call to `{}`",
                            sig.param_names[i], i, callee
                        ),
                        Some(format!(
                            "Add a `{}:` named argument or a positional argument for this \
                             parameter",
                            sig.param_names[i]
                        )),
                        Some(location.clone()),
                        "FUNC011",
                    ));
                }
            }
        }
        Ok(result)
    }

    /// Build HIR expressions from a raw argument list, resolving named arguments
    /// to positional order when the signature is known.
    ///
    /// When the signature is `None` (unknown callee — e.g., an imported function or
    /// a built-in), named arguments are not allowed and we emit a FUNC008 error if
    /// any are present.
    fn build_call_args(
        &mut self,
        callee: &str,
        args: &[Expression],
        location: &SourceLocation,
    ) -> Result<Vec<HirExpression>, CompilerError> {
        if !Self::has_named_args(args) {
            // Fast path: no named args; build directly.
            return args
                .iter()
                .map(|a| self.build_expression(a))
                .collect::<Result<Vec<_>, _>>();
        }

        // Look up the callee's signature.
        let sig = self.named_arg_registry.get(callee).cloned();
        match sig {
            None => {
                // Unknown callee — named args not supported (FUNC008).
                Err(CompilerError::semantic_error_with_code(
                    format!(
                        "FUNC008: named arguments are not supported for unknown or built-in \
                         function `{}`; only user-defined functions with known parameter lists \
                         support named arguments",
                        callee
                    ),
                    Some("Remove the named argument labels".to_string()),
                    Some(location.clone()),
                    "FUNC008",
                ))
            }
            Some(sig_owned) => {
                // Resolve to positional order.
                let ordered = Self::resolve_named_args(callee, &sig_owned, args, location)?;
                // Now build each expression in canonical order.
                ordered
                    .iter()
                    .map(|expr| {
                        // Unwrap NamedArgBinding to get the inner value expression.
                        let inner = if let Expression::NamedArgBinding { value, .. } = expr {
                            value.as_ref()
                        } else {
                            *expr
                        };
                        self.build_expression(inner)
                    })
                    .collect::<Result<Vec<_>, _>>()
            }
        }
    }

    /// Validate that the five core program sections appear in the required order:
    /// import → start → state → class → functions.
    ///
    /// Auxiliary items (watch, screen, framework, apply, private) are exempt from
    /// this ordering rule, as defined by foundation/spec/grammar.ebnf §6 "TOP-LEVEL DECLARATIONS".
    ///
    /// Returns `Err` with a descriptive `CompilerError` if a core section appears
    /// before a section that is supposed to precede it.
    fn validate_section_order(program: &Program) -> Result<(), CompilerError> {
        /// Numeric rank for the five ordered sections.  Auxiliary sections
        /// return `None` and are skipped during the scan.
        fn section_rank(stmt: &Statement) -> Option<(u8, &'static str, Option<SourceLocation>)> {
            match stmt {
                Statement::Import { location, .. } => Some((0, "import", location.clone())),
                // The start: block is represented as FunctionsBlock containing "start",
                // or directly as a standalone start function in program.start_function.
                // In the statement stream the start block appears as FunctionsBlock
                // where the first function is named "start".
                Statement::FunctionsBlock {
                    functions,
                    location,
                    ..
                } => {
                    if functions.iter().any(|f| f.name == "start") {
                        Some((1, "start", location.clone()))
                    } else {
                        Some((4, "functions", location.clone()))
                    }
                }
                Statement::StateBlockStmt { location, .. } => Some((2, "state", location.clone())),
                Statement::ClassDefinition { location, .. } => Some((3, "class", location.clone())),
                // Auxiliary — exempt from ordering.
                Statement::WatchBlockStmt { .. }
                | Statement::ScreenBlockStmt { .. }
                | Statement::ScreenBlock { .. }
                | Statement::FrameworkBlock { .. }
                | Statement::TestsBlock { .. } => None,
                _ => None,
            }
        }

        let mut highest_rank_seen: i8 = -1;
        let mut highest_name_seen: &'static str = "";

        for stmt in &program.statements {
            if let Some((rank, name, loc)) = section_rank(stmt) {
                if (rank as i8) < highest_rank_seen {
                    // This section appears after a section with a higher rank — violation.
                    let order_str = "import → start → state → class → functions";
                    return Err(CompilerError::syntax_error(
                        format!(
                            "'{name}' section must appear before '{highest_name_seen}' section \
                             (spec requires: {order_str})"
                        ),
                        Some(format!(
                            "Move the '{name}:' block so it appears before '{highest_name_seen}:'"
                        )),
                        loc,
                    ));
                }
                if (rank as i8) > highest_rank_seen {
                    highest_rank_seen = rank as i8;
                    highest_name_seen = name;
                }
            }
        }

        Ok(())
    }

    /// Build HIR from an AST program
    pub fn build_hir(&mut self, program: Program) -> Result<HirValidationResult, CompilerError> {
        // Enforce the spec-mandated section ordering before any other processing.
        Self::validate_section_order(&program)?;

        // Pre-scan phase: populate the named-argument signature registry so that
        // named args can be validated and reordered when expressions are lowered.
        self.prescan_signatures(&program);

        // Pre-scan state initializers so that `reset <name>` statements lowered later
        // can expand inline to an assignment of the original initializer expression.
        // Top-level `state:` is the only scope `reset name` can target outside of a
        // screen block (per grammar.ebnf reset_statement = "reset" , ( "state" | identifier )).
        if let Some(state_block) = &program.state {
            for decl in &state_block.declarations {
                self.state_initializers
                    .insert(decl.name.clone(), decl.initializer.clone());
            }
        }

        let mut functions = Vec::new();
        let mut classes = Vec::new();
        let mut start_function = None;
        let mut imports = Vec::new();
        let mut tests: Vec<HirTest> = Vec::new();
        // Top-level `validate name:` blocks are desugared into HIR statements that must be
        // prepended to the start function's body (schemas are initialized before first use).
        let mut validate_preamble: Vec<HirStatement> = Vec::new();

        // Process top-level statements
        for statement in &program.statements {
            match statement {
                Statement::FunctionsBlock {
                    functions: func_list,
                    ..
                } => {
                    for func in func_list {
                        let hir_func = self.build_function(func)?;
                        if func.name == "start" {
                            start_function = Some(hir_func);
                        } else {
                            functions.push(hir_func);
                        }
                    }
                }
                Statement::ClassDefinition { class, .. } => {
                    classes.push(self.build_class(class)?);
                }
                Statement::Import {
                    imports: import_list,
                    ..
                } => {
                    for import_item in import_list {
                        // File path imports ("./module.cln") are resolved by the multi-file
                        // compiler before HIR is built — skip them here to avoid creating
                        // HirImport entries with empty module names (SEM007).
                        if import_item.is_file_import {
                            continue;
                        }

                        // Parse import name to separate module and symbol
                        // Examples:
                        //   "Math" → module: "Math", items: None (whole module)
                        //   "math.sqrt" → module: "math", items: Some(["sqrt"]) (specific symbol)
                        //   "Utils as U" → module: "Utils", items: None, (alias handled separately)
                        //   "Json.decode as jd" → module: "Json", items: Some(["decode"]), (alias handled separately)

                        let (module_name, symbol_items) =
                            if let Some(dot_pos) = import_item.name.find('.') {
                                // Contains dot - import specific symbol(s)
                                let module = &import_item.name[..dot_pos];
                                let symbol = &import_item.name[dot_pos + 1..];
                                (module.to_string(), Some(vec![symbol.to_string()]))
                            } else {
                                // No dot - import whole module
                                (import_item.name.clone(), None)
                            };

                        imports.push(HirImport {
                            module_name,
                            items: symbol_items,
                            location: SourceLocation::default(),
                        });
                    }
                }
                Statement::ValidateDeclaration { schema, location } => {
                    // Top-level `validate name:` blocks desugar into validator.* builder calls.
                    // These are prepended to the start function's body so that the schema
                    // variable is in scope when `.check` is used later in start:.
                    let loc = location.clone().unwrap_or_default();
                    let mut expanded = self.desugar_validate_declaration(schema, &loc)?;
                    validate_preamble.append(&mut expanded);
                }
                Statement::TestsBlock {
                    tests: test_cases,
                    location,
                } => {
                    // Lower each test case into a HirTest node whose body returns
                    // (test_expression == expected_value) as a boolean.
                    let loc = location.clone().unwrap_or_default();
                    for (idx, test_case) in test_cases.iter().enumerate() {
                        let test_loc = test_case.location.clone().unwrap_or_else(|| loc.clone());
                        match &test_case.kind {
                            crate::ast::TestCaseKind::Expression {
                                test_expression,
                                expected_value,
                            } => {
                                let lhs = self.build_expression(test_expression)?;
                                let rhs = self.build_expression(expected_value)?;
                                let equality = HirExpression::BinaryOp {
                                    left: Box::new(lhs),
                                    op: HirBinaryOp::Equal,
                                    right: Box::new(rhs),
                                    location: test_loc.clone(),
                                };
                                let body = HirBlock {
                                    statements: vec![HirStatement::Return {
                                        value: Some(equality),
                                        location: test_loc.clone(),
                                    }],
                                    location: test_loc.clone(),
                                };
                                let name = test_case
                                    .description
                                    .clone()
                                    .unwrap_or_else(|| format!("test_{}", idx));
                                tests.push(HirTest {
                                    name,
                                    description: test_case.description.clone(),
                                    body,
                                    location: test_loc,
                                });
                            }
                            crate::ast::TestCaseKind::Endpoint(endpoint) => {
                                let name = test_case
                                    .description
                                    .clone()
                                    .unwrap_or_else(|| format!("test_{}", idx));
                                let body =
                                    self.build_endpoint_test_body(endpoint, test_loc.clone())?;
                                tests.push(HirTest {
                                    name,
                                    description: test_case.description.clone(),
                                    body,
                                    location: test_loc,
                                });
                            }
                        }
                    }
                }
                _ => {
                    // Handle other top-level statements if needed
                }
            }
        }

        // Process imports from program.imports (top-level import declarations)
        // The parser stores `import Module` statements in program.imports, not in statements.
        for import_item in &program.imports {
            // File path imports ("./module.cln") are resolved by the multi-file compiler
            // before HIR is built — skip them here to avoid SEM007 (empty module name).
            if import_item.is_file_import {
                continue;
            }

            let (module_name, symbol_items) = if let Some(dot_pos) = import_item.name.find('.') {
                let module = &import_item.name[..dot_pos];
                let symbol = &import_item.name[dot_pos + 1..];
                (module.to_string(), Some(vec![symbol.to_string()]))
            } else {
                (import_item.name.clone(), None)
            };
            imports.push(crate::hir::HirImport {
                module_name,
                items: symbol_items,
                location: SourceLocation::default(),
            });
        }

        // Process standalone functions from program.functions
        for func in &program.functions {
            let hir_func = self.build_function(func)?;
            if func.name == "start" {
                start_function = Some(hir_func);
            } else {
                functions.push(hir_func);
            }
        }

        // Process classes from program.classes
        for class in &program.classes {
            classes.push(self.build_class(class)?);
        }

        // Handle the start function if it exists
        if let Some(start_func) = &program.start_function {
            start_function = Some(self.build_function(start_func)?);
        }

        // Process test cases from program.tests (parser stores them directly, not in statements).
        // Each TestCase becomes a HirTest whose body is a single Return(lhs == rhs).
        for (idx, test_case) in program.tests.iter().enumerate() {
            let test_loc = test_case.location.clone().unwrap_or_default();
            match &test_case.kind {
                crate::ast::TestCaseKind::Expression {
                    test_expression,
                    expected_value,
                } => {
                    let lhs = self.build_expression(test_expression)?;
                    let rhs = self.build_expression(expected_value)?;
                    let equality = HirExpression::BinaryOp {
                        left: Box::new(lhs),
                        op: HirBinaryOp::Equal,
                        right: Box::new(rhs),
                        location: test_loc.clone(),
                    };
                    let body = HirBlock {
                        statements: vec![HirStatement::Return {
                            value: Some(equality),
                            location: test_loc.clone(),
                        }],
                        location: test_loc.clone(),
                    };
                    let name = test_case
                        .description
                        .clone()
                        .unwrap_or_else(|| format!("test_{}", idx));
                    tests.push(HirTest {
                        name,
                        description: test_case.description.clone(),
                        body,
                        location: test_loc,
                    });
                }
                crate::ast::TestCaseKind::Endpoint(endpoint) => {
                    let name = test_case
                        .description
                        .clone()
                        .unwrap_or_else(|| format!("test_{}", idx));
                    let body = self.build_endpoint_test_body(endpoint, test_loc.clone())?;
                    tests.push(HirTest {
                        name,
                        description: test_case.description.clone(),
                        body,
                        location: test_loc,
                    });
                }
            }
        }

        // Process state block if present
        let state = if let Some(ast_state) = &program.state {
            Some(self.build_state_block(ast_state)?)
        } else {
            None
        };

        // Process watch blocks
        let watch_blocks = program
            .watch_blocks
            .iter()
            .map(|wb| self.build_watch_block(wb))
            .collect::<Result<Vec<_>, _>>()?;

        // Process external functions (WASM imports)
        let externals = program
            .externals
            .iter()
            .map(|ext| self.build_external_function(ext))
            .collect::<Result<Vec<_>, _>>()?;

        // Process screen blocks (each has its own local state scope for SCOPE005)
        let mut screen_blocks: Vec<crate::hir::HirScreenBlock> = Vec::new();
        for stmt in &program.screen_blocks {
            if let crate::ast::Statement::ScreenBlockStmt {
                name,
                state: screen_state,
                watch_blocks: screen_watches,
                functions: screen_fns,
                location,
            } = stmt
            {
                let hir_state = if let Some(ast_state) = screen_state {
                    Some(self.build_state_block(ast_state)?)
                } else {
                    None
                };
                let hir_watches = screen_watches
                    .iter()
                    .map(|wb| self.build_watch_block(wb))
                    .collect::<Result<Vec<_>, _>>()?;
                let mut hir_fns = screen_fns
                    .iter()
                    .map(|f| self.build_function(f))
                    .collect::<Result<Vec<_>, _>>()?;
                // Set owner_screen on each function so the resolver can enforce SCOPE005
                // while resolving the function body, and promote them to the global
                // function list so they are callable from start: and other functions.
                for hir_fn in hir_fns.iter_mut() {
                    hir_fn.owner_screen = Some(name.clone());
                    functions.push(hir_fn.clone());
                }
                screen_blocks.push(crate::hir::HirScreenBlock {
                    name: name.clone(),
                    state: hir_state,
                    watch_blocks: hir_watches,
                    functions: hir_fns,
                    location: location.clone().unwrap_or_default(),
                });
            }
        }

        // Prepend top-level validate schema initializations to the start function body.
        // This ensures schema variables are declared and initialized before any `.check` usage.
        if !validate_preamble.is_empty() {
            if let Some(ref mut start_fn) = start_function {
                let mut new_stmts = validate_preamble;
                new_stmts.append(&mut start_fn.body.statements);
                start_fn.body.statements = new_stmts;
            }
        }

        // Append any CPS continuation functions generated during `later + api.*` lowering.
        functions.extend(std::mem::take(&mut self.pending_functions));

        let hir_program = HirProgram {
            functions,
            classes,
            start_function,
            imports,
            tests,
            state,
            watch_blocks,
            externals,
            screen_blocks,
            location: program.location.unwrap_or_default(),
        };

        Ok(HirValidationResult {
            hir: hir_program,
            warnings: self.warnings.clone(),
            type_inference_count: self.type_inference_counter,
        })
    }

    /// Convert AST function to HIR function
    fn build_function(&mut self, func: &Function) -> Result<HirFunction, CompilerError> {
        let parameters = func
            .parameters
            .iter()
            .map(|param| self.build_parameter(param))
            .collect::<Result<Vec<_>, _>>()?;

        let return_type = if func.return_type == Type::Void {
            None
        } else {
            Some(self.build_type(&func.return_type)?)
        };

        let saved_fn_name = std::mem::replace(&mut self.current_function_name, func.name.clone());
        let body = self.build_block(&func.body)?;
        self.current_function_name = saved_fn_name;

        Ok(HirFunction {
            name: func.name.clone(),
            parameters,
            return_type,
            body,
            is_start: func.name == "start",
            is_private: func.visibility == crate::ast::Visibility::Private,
            owner_screen: None, // Set to Some(screen_name) when building screen functions
            location: func.location.clone().unwrap_or_default(),
        })
    }

    /// Convert AST external function to HIR external function
    fn build_external_function(
        &mut self,
        ext: &crate::ast::ExternalFunction,
    ) -> Result<HirExternalFunction, CompilerError> {
        let parameters = ext
            .parameters
            .iter()
            .map(|param| self.build_parameter(param))
            .collect::<Result<Vec<_>, _>>()?;

        let return_type = self.build_type(&ext.return_type)?;

        Ok(HirExternalFunction {
            name: ext.name.clone(),
            parameters,
            return_type,
            module: ext.module.clone(),
            location: ext.location.clone().unwrap_or_default(),
        })
    }

    /// Convert AST class to HIR class
    fn build_class(&mut self, class: &Class) -> Result<HirClass, CompilerError> {
        let fields = class
            .fields
            .iter()
            .map(|field| self.build_field(field))
            .collect::<Result<Vec<_>, _>>()?;

        let constructor = if let Some(ctor) = &class.constructor {
            Some(self.build_constructor(ctor, &class.fields)?)
        } else {
            None
        };

        let methods = class
            .methods
            .iter()
            .map(|method| self.build_method(method))
            .collect::<Result<Vec<_>, _>>()?;

        // Build class always: block expressions
        let invariants = class
            .invariants
            .iter()
            .map(|expr| self.build_expression(expr))
            .collect::<Result<Vec<_>, _>>()?;

        Ok(HirClass {
            name: class.name.clone(),
            // Populate generic type parameters from the AST class definition
            type_parameters: class.type_parameters.clone(),
            parent: class.base_class.clone(),
            fields,
            constructor,
            methods,
            invariants,
            location: class.location.clone().unwrap_or_default(),
        })
    }

    /// Convert AST field to HIR field
    fn build_field(&mut self, field: &crate::ast::Field) -> Result<HirField, CompilerError> {
        let field_type = self.build_type(&field.type_)?;
        let initializer = if let Some(init) = &field.default_value {
            Some(self.build_expression(init)?)
        } else {
            None
        };

        Ok(HirField {
            name: field.name.clone(),
            field_type,
            initializer,
            is_private: field.visibility == crate::ast::Visibility::Private,
            location: SourceLocation::default(),
        })
    }

    /// Convert AST constructor to HIR constructor
    fn build_constructor(
        &mut self,
        ctor: &Constructor,
        class_fields: &[crate::ast::Field],
    ) -> Result<HirConstructor, CompilerError> {
        let parameters = ctor
            .parameters
            .iter()
            .map(|param| self.build_parameter(param))
            .collect::<Result<Vec<_>, _>>()?;

        let mut body = self.build_block(&ctor.body)?;

        // NOTE: Auto-storing fields feature
        // When constructor body is empty and parameter names match field names,
        // automatically generate field assignments: field = parameter
        if body.statements.is_empty() {
            let mut auto_assignments = Vec::new();

            for param in &ctor.parameters {
                // Check if there's a field with matching name
                if let Some(_field) = class_fields.iter().find(|f| f.name == param.name) {
                    // Generate: field = parameter
                    let assignment = HirStatement::Assignment {
                        target: HirLValue::Variable {
                            name: param.name.clone(),
                            location: SourceLocation::default(),
                        },
                        value: HirExpression::Variable {
                            name: param.name.clone(),
                            location: SourceLocation::default(),
                        },
                        location: SourceLocation::default(),
                    };
                    auto_assignments.push(assignment);
                }
            }

            body.statements = auto_assignments;
        }

        Ok(HirConstructor {
            parameters,
            body,
            location: ctor.location.clone().unwrap_or_default(),
        })
    }

    /// Convert AST method to HIR method  
    fn build_method(&mut self, method: &Function) -> Result<HirMethod, CompilerError> {
        let parameters = method
            .parameters
            .iter()
            .map(|param| self.build_parameter(param))
            .collect::<Result<Vec<_>, _>>()?;

        let return_type = self.build_type(&method.return_type)?;
        let body = self.build_block(&method.body)?;

        Ok(HirMethod {
            name: method.name.clone(),
            parameters,
            return_type,
            body,
            is_private: method.visibility == crate::ast::Visibility::Private,
            location: method.location.clone().unwrap_or_default(),
        })
    }

    /// Convert AST parameter to HIR parameter
    fn build_parameter(&mut self, param: &Parameter) -> Result<HirParameter, CompilerError> {
        let param_type = self.build_type(&param.type_)?;
        let default_value = if let Some(default_expr) = &param.default_value {
            Some(self.build_expression(default_expr)?)
        } else {
            None
        };

        Ok(HirParameter {
            name: param.name.clone(),
            param_type,
            default_value,
            location: SourceLocation::default(),
        })
    }

    /// Convert AST type to HIR type
    fn build_type(&mut self, ast_type: &Type) -> Result<HirType, CompilerError> {
        match ast_type {
            Type::Boolean => Ok(HirType::Boolean),
            Type::Integer => Ok(HirType::Integer),
            Type::Number => Ok(HirType::Number),
            Type::String => Ok(HirType::String),
            Type::Void => Ok(HirType::Void),
            Type::IntegerSized { bits, unsigned } => match (bits, unsigned) {
                (8, false) => Ok(HirType::Integer8),
                (8, true) => Ok(HirType::Integer8u),
                (16, false) => Ok(HirType::Integer16),
                (16, true) => Ok(HirType::Integer16u),
                (32, false) => Ok(HirType::Integer32),
                (32, true) => Ok(HirType::Integer32u),
                (64, false) => Ok(HirType::Integer64),
                (64, true) => Ok(HirType::Integer64u),
                _ => Err(CompilerError::syntax_error(
                    format!("Unsupported integer size: {bits} bits, unsigned: {unsigned}"),
                    Some("Only 8, 16, 32, and 64 bit integers are supported".to_string()),
                    None,
                )),
            },
            Type::NumberSized { bits } => match bits {
                32 => Ok(HirType::Number32),
                64 => Ok(HirType::Number64),
                _ => Err(CompilerError::syntax_error(
                    format!("Unsupported number size: {bits} bits"),
                    Some("Only 32 and 64 bit numbers are supported".to_string()),
                    None,
                )),
            },
            Type::List(inner, _behavior) => {
                // Behaviour is carried separately on `HirStatement::VariableDeclaration`
                // (set when the var-decl path lowers the AST type). HirType itself
                // is intentionally behaviour-free so list values flowing through the
                // type system don't need to track it everywhere.
                let inner_type = self.build_type(inner)?;
                Ok(HirType::List(Box::new(inner_type)))
            }
            Type::Matrix(inner) => {
                let inner_type = self.build_type(inner)?;
                Ok(HirType::Matrix(Box::new(inner_type)))
            }
            Type::Pairs(key_type, value_type) => {
                let key_hir_type = self.build_type(key_type)?;
                let value_hir_type = self.build_type(value_type)?;
                Ok(HirType::Pairs(
                    Box::new(key_hir_type),
                    Box::new(value_hir_type),
                ))
            }
            Type::Object(name) | Type::Class { name, .. } => Ok(HirType::Named {
                name: name.clone(),
                location: SourceLocation::default(),
            }),
            Type::Any => {
                // 'any' is the top type — compatible with all other types.
                // Map to HirType::Any so the type checker accepts it everywhere,
                // and so HirValidator::validate_type does not reject it as an
                // unknown Named type (it falls through to the _ arm → valid).
                Ok(HirType::Any)
            }
            Type::Handler => {
                // handler is a first-class function reference — at WASM level it is
                // an i32 function-table index, so we map it to Integer in HIR.
                Ok(HirType::Integer)
            }
            _ => {
                // For unsupported types, create an inferred type for now
                self.type_inference_counter += 1;
                Ok(HirType::Inferred {
                    id: self.type_inference_counter,
                    location: SourceLocation::default(),
                })
            }
        }
    }

    /// Convert statements to HIR block
    fn build_block(&mut self, statements: &[Statement]) -> Result<HirBlock, CompilerError> {
        // Enter a nested scope: apply blocks and imports are now forbidden.
        self.scope_depth += 1;
        let mut result = self.build_block_inner(statements);
        self.scope_depth -= 1;

        // Post-pass: detect the `string acc = ""; while … { acc = acc + … }`
        // pattern and rewrite it to use a doubling-capacity string builder.
        // Resolves CMP-SSR-MALLOC-OOM-PAGE-RENDER by converting the O(n²)
        // accumulator pattern (each iteration strands the old `acc`) into
        // an O(n) one.
        //
        // Runs on every lowered block. Because `build_block` recurses for
        // function bodies, method bodies, loop bodies, and if branches,
        // inner blocks are rewritten before their enclosing ones — so an
        // outer accumulator loop containing an inner accumulator loop
        // (e.g. the SSR repro) gets both rewritten.
        if let Ok(block) = &mut result {
            // Dual-accumulator rewrite (COMPILER-MEM-ALLOC-NO-GROW-RECURRENCE,
            // fp b80c2f907c71). Detects the `expand_endpoints`-style pattern
            // where two string accumulators (`result` and `route_calls`) are
            // both appended in a loop, causing O(N²) host-arena growth.
            // Wraps each loop iteration in `_arena_scope_push/_arena_scope_pop`
            // so per-iteration intermediate strings are reclaimed in O(1).
            // MUST run BEFORE the single-accumulator rewrite: when one of the
            // two accumulators has an empty-string initializer, the single-acc
            // pass would eagerly consume it (rewriting to `__sb_N_*`) before the
            // dual matcher can see the paired pattern.  Running dual first gives
            // it first pick; any remaining lone accumulator is then handled by
            // the single pass.
            self.rewrite_dual_accumulator_loops(&mut block.statements);
            self.rewrite_string_accumulator_loops(&mut block.statements);
            // Single-shot (loop-free) accumulator rewrite — Step 4.
            // Catches plugin-emitted html: block helpers like:
            //   string __html = ""
            //   __html = __html + e1 + e2 + ... + eN
            //   return __html
            // and user-written render helpers with the same shape. These
            // are called from inside SSR loops in the caller; each call
            // would otherwise allocate N intermediate strings on the main
            // heap. The single-shot rewrite turns N concat calls into one
            // string_builder_new + N string_builder_append + one
            // string_builder_finalize, mirroring what javac/Kotlin/Go
            // do for chained concatenation regardless of loop context.
            self.rewrite_string_accumulator_singleshot(&mut block.statements);
        }
        result
    }

    /// Inner implementation of build_block, called after scope_depth has been incremented.
    fn build_block_inner(&mut self, statements: &[Statement]) -> Result<HirBlock, CompilerError> {
        let mut hir_statements = Vec::new();
        let mut stmt_idx = 0;

        while stmt_idx < statements.len() {
            let stmt = &statements[stmt_idx];

            // ----------------------------------------------------------------
            // CPS transform: `later varName = api.method(args...)` splits the
            // function at this point. All following statements become a new
            // exported continuation function called by the browser runtime when
            // the response arrives. Spec: grammar.ebnf §4.9 later_assignment.
            //
            // `api.get(url)` is parsed as MethodCall { object: Variable("api"), method: "get" }
            // by the token parser (dot-access on a simple identifier). We detect both
            // MethodCall and StaticMethodCall forms here.
            // ----------------------------------------------------------------
            if let Statement::LaterAssignment {
                variable,
                expression,
                location,
            } = stmt
            {
                // Extract (namespace, method_name, user_args) from either form.
                let cps_parts: Option<(String, String, &[Expression])> = match expression {
                    // Primary form: api.get(url) parsed as NamespaceCall by the token parser
                    Expression::NamespaceCall {
                        namespace,
                        function,
                        arguments,
                        ..
                    } => {
                        if namespace == "api" {
                            Some((namespace.clone(), function.clone(), arguments.as_slice()))
                        } else {
                            None
                        }
                    }
                    // Fallback: MethodCall { object: Variable("api"), method: "get" }
                    Expression::MethodCall {
                        object,
                        method,
                        arguments,
                        ..
                    } => {
                        if let Expression::Variable(ns) = object.as_ref() {
                            if ns == "api" {
                                Some((ns.clone(), method.clone(), arguments.as_slice()))
                            } else {
                                None
                            }
                        } else {
                            None
                        }
                    }
                    // Fallback: StaticMethodCall form
                    Expression::StaticMethodCall {
                        namespace,
                        class_name,
                        method,
                        arguments,
                        ..
                    } => {
                        let ns = if namespace.is_empty() {
                            class_name.as_str()
                        } else {
                            namespace[0].as_str()
                        };
                        if ns == "api" {
                            Some((ns.to_string(), method.clone(), arguments.as_slice()))
                        } else {
                            None
                        }
                    }
                    _ => None,
                };

                if let Some((api_ns, api_method, user_args)) = cps_parts {
                    let loc = location.clone().unwrap_or_default();

                    // Generate a unique name for the continuation function.
                    let cont_name = format!(
                        "__later_{}_{}",
                        self.later_counter, self.current_function_name
                    );
                    self.later_counter += 1;

                    // Register the response variable so build_expression can
                    // substitute result.ok → api.ok(), result.json(p) → api.json(p), etc.
                    self.api_response_vars
                        .insert(variable.clone(), api_ns.clone());

                    // Build the continuation body from all remaining statements.
                    let continuation_stmts = &statements[stmt_idx + 1..];
                    let cont_body = self.build_block_inner(continuation_stmts)?;

                    // Unregister the response variable (scoped to this continuation only).
                    self.api_response_vars.remove(variable);

                    // Store the parent function name before overwriting it for the continuation.
                    let saved_fn_name =
                        std::mem::replace(&mut self.current_function_name, cont_name.clone());

                    self.pending_functions.push(crate::hir::HirFunction {
                        name: cont_name.clone(),
                        parameters: vec![],
                        return_type: None,
                        body: cont_body,
                        is_start: false,
                        is_private: false,
                        owner_screen: None,
                        location: loc.clone(),
                    });

                    self.current_function_name = saved_fn_name;

                    // Build the user-provided arguments to api.method(…).
                    let mut hir_args: Vec<crate::hir::HirExpression> = user_args
                        .iter()
                        .map(|arg| self.build_expression(arg))
                        .collect::<Result<Vec<_>, _>>()?;

                    // Append the generated continuation name as the handler argument.
                    hir_args.push(crate::hir::HirExpression::Literal {
                        value: crate::ast::Value::String(cont_name),
                        location: loc.clone(),
                    });

                    // Replace the LaterAssignment with a plain call to api.method(…, handlerName).
                    hir_statements.push(crate::hir::HirStatement::Expression {
                        expression: crate::hir::HirExpression::StaticMethodCall {
                            namespace: vec![],
                            class_name: api_ns,
                            method: api_method,
                            arguments: hir_args,
                            location: loc.clone(),
                        },
                        location: loc,
                    });

                    // All remaining statements are now in the continuation; stop here.
                    break;
                }
            }

            // Validate that imports do not appear inside nested scopes.
            // Apply blocks (type, constant, function, method) are valid inside function bodies per the spec
            // (grammar.ebnf line ~426: statement includes apply_block).
            if let Statement::Import { location, .. } = stmt {
                let loc = location.clone().unwrap_or_default();
                return Err(CompilerError::validation_error(
                    "import statements must appear at the top level of a program, not inside a function or block",
                    loc,
                ));
            }

            // Special handling for TypeApplyBlock - expand into multiple statements
            if let Statement::TypeApplyBlock {
                type_,
                assignments,
                location,
            } = stmt
            {
                tracing::debug!(
                    type_ = ?type_,
                    assignments_count = assignments.len(),
                    "Expanding TypeApplyBlock into variable declarations"
                );
                // Convert each assignment in the apply block to a variable declaration
                for assignment in assignments {
                    let var_type = self.build_type(type_)?;
                    let init_expr = if let Some(init) = &assignment.initializer {
                        Some(self.build_expression(init)?)
                    } else {
                        None
                    };

                    tracing::debug!(
                        variable_name = %assignment.name,
                        var_type = ?var_type,
                        "Created VariableDeclaration from TypeApplyBlock"
                    );

                    let decl_loc = location.clone().unwrap_or_default();
                    hir_statements.push(HirStatement::VariableDeclaration {
                        name: assignment.name.clone(),
                        var_type,
                        initializer: init_expr,
                        is_mutable: true, // Apply blocks create mutable variables
                        location: decl_loc.clone(),
                    });
                    // Inject behavior flags for list type apply blocks with non-Default behavior.
                    if let Type::List(_, behavior) = type_ {
                        if *behavior != ListBehavior::Default {
                            hir_statements.push(self.make_set_behavior_stmt(
                                &assignment.name,
                                *behavior,
                                decl_loc,
                            ));
                        }
                    }
                }
            } else if let Statement::ConstantApplyBlock {
                constants,
                location,
            } = stmt
            {
                // Convert each constant in the apply block to a variable declaration
                // Constants are treated as immutable variables in HIR
                for constant in constants {
                    let var_type = self.build_type(&constant.type_)?;
                    let init_expr = Some(self.build_expression(&constant.value)?);

                    // Track this as a constant binding for resolver
                    self.constant_bindings.insert(constant.name.clone());

                    hir_statements.push(HirStatement::VariableDeclaration {
                        name: constant.name.clone(),
                        var_type,
                        initializer: init_expr,
                        is_mutable: false, // Constant apply blocks create immutable variables
                        location: location.clone().unwrap_or_default(),
                    });
                }
            } else if let Statement::ValidateDeclaration { schema, location } = stmt {
                // Desugar `validate name:` into a sequence of validator.* calls that build
                // the ValidationRules object and store it as a local variable.
                let loc = location.clone().unwrap_or_default();
                let mut expanded = self.desugar_validate_declaration(schema, &loc)?;
                hir_statements.append(&mut expanded);
            } else if let Statement::ValidateCheck { check, location } = stmt {
                // Desugar `schemaName.check expr:` into a validator.run + isOk branch.
                let loc = location.clone().unwrap_or_default();
                let mut expanded = self.desugar_validate_check(check, &loc)?;
                hir_statements.append(&mut expanded);
            } else if let Statement::Error { message, location } = stmt {
                // Desugar `error("msg")` into a print-then-trap pair so:
                //   1. The message string literal is embedded in the data
                //      section (would otherwise vanish under DCE).
                //   2. The message is observable on the host's stdout
                //      before the trap fires.
                //   3. `require false` produces the unconditional WASM
                //      trap that callers of `error()` expect.
                //
                // Pre-fix `Statement::Error` fell through the wildcard
                // `_ => Ok(HirStatement::Expression { Void })` arm in
                // `build_statement`, silently becoming a no-op — every
                // `error("...")` call disappeared, its argument string
                // vanished from the binary, and execution continued past
                // the would-be trap. Reported as
                // COMPILER-SYNTHETIC-MODULE-START-BLOCK-DROPPED (the
                // dropped synthetic module's start: body was just
                // `error("diagnostic fired!")`, which lowered to nothing).
                let loc = location.clone().unwrap_or_default();
                let message_expr = self.build_expression(message)?;
                hir_statements.push(HirStatement::Print {
                    expression: message_expr,
                    newline: true,
                    location: loc.clone(),
                });
                hir_statements.push(HirStatement::Require {
                    condition: HirExpression::Literal {
                        value: Value::Boolean(false),
                        location: loc.clone(),
                    },
                    location: loc,
                });
            } else {
                // Regular statement processing
                hir_statements.push(self.build_statement(stmt)?);
                // Inject behavior flags for list declarations with non-Default behavior.
                if let Statement::VariableDecl {
                    name,
                    type_: Type::List(_, behavior),
                    location,
                    ..
                } = stmt
                {
                    if *behavior != ListBehavior::Default {
                        let loc = location.clone().unwrap_or_default();
                        hir_statements.push(self.make_set_behavior_stmt(name, *behavior, loc));
                    }
                }
            }

            stmt_idx += 1;
        }

        Ok(HirBlock {
            statements: hir_statements,
            location: SourceLocation::default(),
        })
    }

    /// Convert AST statement to HIR statement
    fn build_statement(&mut self, stmt: &Statement) -> Result<HirStatement, CompilerError> {
        match stmt {
            Statement::VariableDecl {
                name,
                type_,
                initializer,
                location,
            } => {
                let var_type = self.build_type(type_)?;
                let init_expr = if let Some(init) = initializer {
                    Some(self.build_expression(init)?)
                } else {
                    None
                };

                Ok(HirStatement::VariableDeclaration {
                    name: name.clone(),
                    var_type,
                    initializer: init_expr,
                    is_mutable: true, // Regular variable declarations are mutable by default
                    location: location.clone().unwrap_or_default(),
                })
            }

            Statement::Assignment {
                target,
                value,
                location,
            } => {
                let loc = location.clone().unwrap_or_default();
                let lvalue = match target {
                    AssignmentTarget::Variable(name) => HirLValue::Variable {
                        name: name.clone(),
                        location: loc.clone(),
                    },
                    AssignmentTarget::Index { collection, index } => {
                        let array_expr = HirExpression::Variable {
                            name: collection.clone(),
                            location: loc.clone(),
                        };
                        let index_expr = self.build_expression(index)?;
                        HirLValue::Index {
                            array: Box::new(array_expr),
                            index: Box::new(index_expr),
                            location: loc.clone(),
                        }
                    }
                    AssignmentTarget::Property { object, path } => {
                        // Build a chain of FieldAccess expressions for nested paths.
                        // For a single-element path `obj.field`, there is exactly one field.
                        // For `obj.a.b`, we nest: FieldAccess(FieldAccess(Variable(obj), a), b).
                        let base = HirExpression::Variable {
                            name: object.clone(),
                            location: loc.clone(),
                        };
                        let (last_field, prefix) = path.split_last().expect(
                            "AssignmentTarget::Property requires at least one path element",
                        );
                        let inner =
                            prefix
                                .iter()
                                .fold(base, |acc, seg| HirExpression::FieldAccess {
                                    object: Box::new(acc),
                                    field: seg.clone(),
                                    location: loc.clone(),
                                });
                        HirLValue::FieldAccess {
                            object: Box::new(inner),
                            field: last_field.clone(),
                            location: loc.clone(),
                        }
                    }
                };
                let hir_value = self.build_expression(value)?;

                Ok(HirStatement::Assignment {
                    target: lvalue,
                    value: hir_value,
                    location: loc,
                })
            }

            Statement::Print {
                expression,
                newline,
                location,
            } => {
                let hir_expr = self.build_expression(expression)?;
                Ok(HirStatement::Print {
                    expression: hir_expr,
                    newline: *newline,
                    location: location.clone().unwrap_or_default(),
                })
            }

            Statement::Return { value, location } => {
                let return_value = if let Some(expr) = value {
                    Some(self.build_expression(expr)?)
                } else {
                    None
                };

                Ok(HirStatement::Return {
                    value: return_value,
                    location: location.clone().unwrap_or_default(),
                })
            }

            Statement::If {
                condition,
                then_branch,
                else_branch,
                location,
            } => {
                let hir_condition = self.build_expression(condition)?;
                let hir_then = self.build_block(then_branch)?;
                let hir_else = if let Some(else_stmts) = else_branch {
                    Some(self.build_block(else_stmts)?)
                } else {
                    None
                };

                Ok(HirStatement::If {
                    condition: hir_condition,
                    then_branch: hir_then,
                    else_branch: hir_else,
                    location: location.clone().unwrap_or_default(),
                })
            }

            Statement::Iterate {
                iterator,
                collection,
                body,
                location,
            } => {
                let hir_iterable = self.build_expression(collection)?;
                let hir_body = self.build_block(body)?;

                Ok(HirStatement::For {
                    variable: iterator.clone(),
                    iterable: hir_iterable,
                    body: hir_body,
                    location: location.clone().unwrap_or_default(),
                })
            }

            Statement::RangeIterate {
                iterator,
                start,
                end,
                step,
                inclusive,
                body,
                location,
            } => {
                // Convert RangeIterate to For with a Range expression as the iterable
                let hir_start = self.build_expression(start)?;
                let hir_end = self.build_expression(end)?;
                let hir_step = if let Some(s) = step {
                    Some(Box::new(self.build_expression(s)?))
                } else {
                    None
                };

                let range_expr = HirExpression::Range {
                    start: Box::new(hir_start),
                    end: Box::new(hir_end),
                    step: hir_step,
                    inclusive: *inclusive,
                    location: location.clone().unwrap_or_default(),
                };

                let hir_body = self.build_block(body)?;

                Ok(HirStatement::For {
                    variable: iterator.clone(),
                    iterable: range_expr,
                    body: hir_body,
                    location: location.clone().unwrap_or_default(),
                })
            }

            Statement::While {
                condition,
                body,
                location,
            } => {
                let hir_condition = self.build_expression(condition)?;
                let hir_body = self.build_block(body)?;

                Ok(HirStatement::While {
                    condition: hir_condition,
                    body: hir_body,
                    location: location.clone().unwrap_or_default(),
                })
            }

            Statement::Expression { expr, location } => {
                let hir_expr = self.build_expression(expr)?;
                Ok(HirStatement::Expression {
                    expression: hir_expr,
                    location: location.clone().unwrap_or_default(),
                })
            }

            Statement::LaterAssignment {
                variable,
                expression,
                location,
            } => {
                let hir_expr = self.build_expression(expression)?;
                Ok(HirStatement::LaterAssignment {
                    variable: variable.clone(),
                    expression: hir_expr,
                    location: location.clone().unwrap_or_default(),
                })
            }

            Statement::Background {
                expression,
                location,
            } => {
                let hir_expr = self.build_expression(expression)?;
                Ok(HirStatement::Background {
                    expression: hir_expr,
                    location: location.clone().unwrap_or_default(),
                })
            }

            Statement::Break { location } => Ok(HirStatement::Break {
                location: location.clone().unwrap_or_default(),
            }),

            Statement::Continue { location } => Ok(HirStatement::Continue {
                location: location.clone().unwrap_or_default(),
            }),

            Statement::Require {
                condition,
                location,
            } => {
                let hir_condition = self.build_expression(condition)?;
                Ok(HirStatement::Require {
                    condition: hir_condition,
                    location: location.clone().unwrap_or_default(),
                })
            }

            Statement::Ensure {
                condition,
                location,
            } => {
                let hir_condition = self.build_expression(condition)?;
                Ok(HirStatement::Ensure {
                    condition: hir_condition,
                    location: location.clone().unwrap_or_default(),
                })
            }

            // reset_statement — lower to inline assignment from the captured state initializer.
            // grammar.ebnf: reset_statement = "reset" , ( "state" | identifier ) ;
            //
            // Host bridges historically left `_state_reset_named` / `_state_reset_all` as
            // no-ops, so `reset <name>` produced no effect at runtime. The initializer is
            // captured during the build_hir pre-scan, so we can rewrite the statement here
            // to `<name> = <initializer>` and bypass the host entirely.
            Statement::ResetStmt { target, location } => {
                let loc = location.clone().unwrap_or_default();
                match target {
                    ResetTarget::AllState => {
                        // `reset state` — fall back to the host bridge for now. Lowering this
                        // inline requires emitting multiple assignments from a single
                        // statement node, which build_statement's single-return shape doesn't
                        // accommodate. Tracked as a follow-up; `reset state` is the rarer
                        // form and most hosts already stub it.
                        Ok(HirStatement::Expression {
                            expression: HirExpression::Call {
                                function: "_state_reset_all".to_string(),
                                arguments: vec![],
                                location: loc.clone(),
                            },
                            location: loc,
                        })
                    }
                    ResetTarget::Variable(name) => {
                        if let Some(init_expr) = self.state_initializers.get(name).cloned() {
                            let value = self.build_expression(&init_expr)?;
                            Ok(HirStatement::Assignment {
                                target: HirLValue::Variable {
                                    name: name.clone(),
                                    location: loc.clone(),
                                },
                                value,
                                location: loc,
                            })
                        } else {
                            // Variable was not declared in any state: block — keep the call
                            // so semantic analysis emits the right diagnostic instead of
                            // silently succeeding on a missing target.
                            Ok(HirStatement::Expression {
                                expression: HirExpression::Call {
                                    function: "_state_reset_named".to_string(),
                                    arguments: vec![HirExpression::Literal {
                                        value: Value::String(name.clone()),
                                        location: loc.clone(),
                                    }],
                                    location: loc.clone(),
                                },
                                location: loc,
                            })
                        }
                    }
                }
            }

            // TypeApplyBlock is handled in build_block() where it can expand into multiple statements
            _ => {
                // For unsupported statements, create a dummy expression statement
                Ok(HirStatement::Expression {
                    expression: HirExpression::Literal {
                        value: Value::Void,
                        location: SourceLocation::default(),
                    },
                    location: SourceLocation::default(),
                })
            }
        }
    }

    /// Convert AST expression to HIR expression
    fn build_expression(&mut self, expr: &Expression) -> Result<HirExpression, CompilerError> {
        match expr {
            Expression::Literal(value) => {
                // NOTE: Array literals must be converted to HirExpression::Array
                // not HirExpression::Literal, otherwise they get converted to Null in type inference
                match value {
                    Value::List(elements) => {
                        // Convert list literal to Array expression
                        let mut hir_elements = Vec::new();
                        for elem in elements {
                            hir_elements
                                .push(self.build_expression(&Expression::Literal(elem.clone()))?);
                        }

                        // Infer element type from first element, or use Void for empty lists
                        let element_type = if let Some(first_elem) = elements.first() {
                            self.value_to_hir_type(first_elem)
                        } else {
                            HirType::Void // Will be inferred from context in type checker
                        };

                        Ok(HirExpression::Array {
                            elements: hir_elements,
                            element_type,
                            location: SourceLocation::default(),
                        })
                    }
                    _ => Ok(HirExpression::Literal {
                        value: value.clone(),
                        location: SourceLocation::default(),
                    }),
                }
            }

            Expression::Variable(name) => Ok(HirExpression::Variable {
                name: name.clone(),
                location: SourceLocation::default(),
            }),

            Expression::Binary(left, op, right) => {
                let hir_left = self.build_expression(left)?;
                let hir_right = self.build_expression(right)?;
                let hir_op = self.convert_binary_op(op);

                Ok(HirExpression::BinaryOp {
                    left: Box::new(hir_left),
                    op: hir_op,
                    right: Box::new(hir_right),
                    location: SourceLocation::default(),
                })
            }

            Expression::Unary(op, operand) => {
                let hir_operand = self.build_expression(operand)?;
                let hir_op = self.convert_unary_op(op);

                Ok(HirExpression::UnaryOp {
                    op: hir_op,
                    operand: Box::new(hir_operand),
                    location: SourceLocation::default(),
                })
            }

            Expression::Call(name, args) => {
                // NOTE: Detect base() calls for parent constructor invocation
                // base() is a special function call that invokes the parent class constructor
                if name == "base" {
                    let hir_args =
                        self.build_call_args("base", args, &SourceLocation::default())?;
                    Ok(HirExpression::BaseCall {
                        arguments: hir_args,
                        location: SourceLocation::default(),
                    })
                } else {
                    let hir_args = self.build_call_args(name, args, &SourceLocation::default())?;
                    Ok(HirExpression::Call {
                        function: name.clone(),
                        arguments: hir_args,
                        location: SourceLocation::default(),
                    })
                }
            }

            Expression::MethodCall {
                object,
                method,
                arguments,
                location,
            } => {
                // CPS substitution: `result.json(path)` → `api.json(path)` etc.
                if let Expression::Variable(var_name) = object.as_ref() {
                    if let Some(ns) = self.api_response_vars.get(var_name.as_str()).cloned() {
                        if let Some(bridge_method) =
                            Self::api_response_method_to_bridge(&ns, method)
                        {
                            let hir_args = arguments
                                .iter()
                                .map(|arg| self.build_expression(arg))
                                .collect::<Result<Vec<_>, _>>()?;
                            return Ok(HirExpression::StaticMethodCall {
                                namespace: vec![],
                                class_name: ns,
                                method: bridge_method,
                                arguments: hir_args,
                                location: location.clone(),
                            });
                        }
                    }
                }

                let hir_object = self.build_expression(object)?;

                // For method calls, attempt named-argument resolution by looking up
                // the method in the registry under the receiver's type name if known.
                // Since we don't have full type information at HIR stage, we try a best-
                // effort lookup: if any class exposes a method with this name and the arg
                // count matches, use that signature.  If multiple matches or none, fall
                // back to an error when named args are present.
                let hir_args = if Self::has_named_args(arguments) {
                    // Attempt resolution: search for `AnyClass::method` in the registry.
                    let candidates: Vec<CallableSignature> = self
                        .named_arg_registry
                        .iter()
                        .filter(|(k, sig)| {
                            k.ends_with(&format!("::{}", method))
                                && sig.param_names.len() == arguments.len()
                        })
                        .map(|(_, v)| v.clone())
                        .collect();

                    match candidates.len() {
                        0 => {
                            return Err(CompilerError::semantic_error_with_code(
                                format!(
                                    "FUNC008: named arguments used in method call `.{}()` but no \
                                     matching method signature was found in any class",
                                    method
                                ),
                                Some(
                                    "Ensure the method is defined in a class visible to this call \
                                     site, or use positional arguments"
                                        .to_string(),
                                ),
                                Some(location.clone()),
                                "FUNC008",
                            ));
                        }
                        1 => {
                            let sig = candidates
                                .into_iter()
                                .next()
                                .expect("invariant: match arm len==1 guarantees one element");
                            let ordered =
                                Self::resolve_named_args(method, &sig, arguments, location)?;
                            ordered
                                .iter()
                                .map(|expr| {
                                    let inner =
                                        if let Expression::NamedArgBinding { value, .. } = expr {
                                            value.as_ref()
                                        } else {
                                            *expr
                                        };
                                    self.build_expression(inner)
                                })
                                .collect::<Result<Vec<_>, _>>()?
                        }
                        _ => {
                            return Err(CompilerError::semantic_error_with_code(
                                format!(
                                    "FUNC008: named arguments in method call `.{}()` are \
                                     ambiguous — multiple classes define a method with this \
                                     name and argument count",
                                    method
                                ),
                                Some(
                                    "Use positional arguments to avoid ambiguity, or qualify \
                                     the receiver type"
                                        .to_string(),
                                ),
                                Some(location.clone()),
                                "FUNC008",
                            ));
                        }
                    }
                } else {
                    arguments
                        .iter()
                        .map(|arg| self.build_expression(arg))
                        .collect::<Result<Vec<_>, _>>()?
                };

                Ok(HirExpression::MethodCall {
                    receiver: Box::new(hir_object),
                    method: method.clone(),
                    arguments: hir_args,
                    location: location.clone(),
                })
            }

            // ChainedMethodCall — foundation/spec/grammar.ebnf `chained_method_call`.
            // Lowered to a left-to-right fold of HirExpression::MethodCall nodes.
            Expression::ChainedMethodCall {
                receiver,
                chain,
                location,
            } => {
                let mut hir_recv = self.build_expression(receiver)?;
                for (method, args) in chain {
                    let hir_args = args
                        .iter()
                        .map(|arg| self.build_expression(arg))
                        .collect::<Result<Vec<_>, _>>()?;
                    hir_recv = HirExpression::MethodCall {
                        receiver: Box::new(hir_recv),
                        method: method.clone(),
                        arguments: hir_args,
                        location: location.clone(),
                    };
                }
                Ok(hir_recv)
            }

            // MultipleMethodCall — foundation/spec/grammar.ebnf `multiple_method_call`.
            // Structurally identical to ChainedMethodCall; lowered the same way.
            Expression::MultipleMethodCall {
                receiver,
                chain,
                location,
            } => {
                let mut hir_recv = self.build_expression(receiver)?;
                for (method, args) in chain {
                    let hir_args = args
                        .iter()
                        .map(|arg| self.build_expression(arg))
                        .collect::<Result<Vec<_>, _>>()?;
                    hir_recv = HirExpression::MethodCall {
                        receiver: Box::new(hir_recv),
                        method: method.clone(),
                        arguments: hir_args,
                        location: location.clone(),
                    };
                }
                Ok(hir_recv)
            }

            // ThreeLevelMethodCall — foundation/spec/grammar.ebnf `three_level_method_call`.
            // `first.second.method(args)` — lowered to nested FieldAccess then MethodCall.
            Expression::ThreeLevelMethodCall {
                first,
                second,
                method,
                arguments,
                location,
            } => {
                let base = HirExpression::Variable {
                    name: first.clone(),
                    location: location.clone(),
                };
                let intermediate = HirExpression::FieldAccess {
                    object: Box::new(base),
                    field: second.clone(),
                    location: location.clone(),
                };
                let hir_args = arguments
                    .iter()
                    .map(|arg| self.build_expression(arg))
                    .collect::<Result<Vec<_>, _>>()?;
                Ok(HirExpression::MethodCall {
                    receiver: Box::new(intermediate),
                    method: method.clone(),
                    arguments: hir_args,
                    location: location.clone(),
                })
            }

            // PropertyMethodCall — foundation/spec/grammar.ebnf `property_method_call`.
            // `obj.a.b...method(args)` — lowered to a chain of FieldAccess then MethodCall.
            Expression::PropertyMethodCall {
                object,
                path,
                method,
                arguments,
                location,
            } => {
                let base = HirExpression::Variable {
                    name: object.clone(),
                    location: location.clone(),
                };
                let receiver = path
                    .iter()
                    .fold(base, |acc, seg| HirExpression::FieldAccess {
                        object: Box::new(acc),
                        field: seg.clone(),
                        location: location.clone(),
                    });
                let hir_args = arguments
                    .iter()
                    .map(|arg| self.build_expression(arg))
                    .collect::<Result<Vec<_>, _>>()?;
                Ok(HirExpression::MethodCall {
                    receiver: Box::new(receiver),
                    method: method.clone(),
                    arguments: hir_args,
                    location: location.clone(),
                })
            }

            Expression::PropertyAccess {
                object,
                property,
                location,
            } => {
                // CPS substitution: `result.ok` → `api.ok()`, `result.status` → `api.status()`, etc.
                if let Expression::Variable(var_name) = object.as_ref() {
                    if let Some(ns) = self.api_response_vars.get(var_name.as_str()).cloned() {
                        if let Some(bridge_method) =
                            Self::api_response_property_to_bridge(&ns, property)
                        {
                            return Ok(HirExpression::StaticMethodCall {
                                namespace: vec![],
                                class_name: ns,
                                method: bridge_method,
                                arguments: vec![],
                                location: location.clone(),
                            });
                        }
                    }
                }

                let hir_object = self.build_expression(object)?;

                Ok(HirExpression::FieldAccess {
                    object: Box::new(hir_object),
                    field: property.clone(),
                    location: location.clone(),
                })
            }

            Expression::ListAccess(array, index) => {
                let hir_array = self.build_expression(array)?;
                let hir_index = self.build_expression(index)?;

                Ok(HirExpression::Index {
                    array: Box::new(hir_array),
                    index: Box::new(hir_index),
                    location: SourceLocation::default(),
                })
            }

            Expression::ObjectCreation {
                class_name,
                arguments,
                location,
            } => {
                // The constructor signature is registered under the class name.
                let hir_args = self.build_call_args(class_name, arguments, location)?;

                Ok(HirExpression::Constructor {
                    class_name: class_name.clone(),
                    arguments: hir_args,
                    location: location.clone(),
                })
            }

            Expression::NamespaceCall {
                namespace,
                function,
                arguments,
                location,
            } => {
                let hir_args = arguments
                    .iter()
                    .map(|arg| self.build_expression(arg))
                    .collect::<Result<Vec<_>, _>>()?;

                Ok(HirExpression::NamespaceCall {
                    namespace: namespace.clone(),
                    function: function.clone(),
                    arguments: hir_args,
                    location: location.clone(),
                })
            }

            Expression::StaticMethodCall {
                namespace,
                class_name,
                method,
                arguments,
                location,
            } => {
                let hir_args = arguments
                    .iter()
                    .map(|arg| self.build_expression(arg))
                    .collect::<Result<Vec<_>, _>>()?;

                Ok(HirExpression::StaticMethodCall {
                    namespace: namespace.clone(),
                    class_name: class_name.clone(),
                    method: method.clone(),
                    arguments: hir_args,
                    location: location.clone(),
                })
            }

            Expression::OnError {
                expression,
                fallback,
                location,
            } => {
                let hir_expression = self.build_expression(expression)?;
                let hir_fallback = self.build_expression(fallback)?;

                Ok(HirExpression::OnError {
                    expression: Box::new(hir_expression),
                    fallback: Box::new(hir_fallback),
                    location: location.clone(),
                })
            }

            Expression::Conditional {
                condition,
                then_expr,
                else_expr,
                location,
            } => {
                let hir_condition = self.build_expression(condition)?;
                let hir_then = self.build_expression(then_expr)?;
                let hir_else = self.build_expression(else_expr)?;

                Ok(HirExpression::Conditional {
                    condition: Box::new(hir_condition),
                    then_expr: Box::new(hir_then),
                    else_expr: Box::new(hir_else),
                    location: location.clone(),
                })
            }

            // NOTE: Handle base() calls from AST
            // The parser creates Expression::BaseCall, so we must handle it here
            Expression::BaseCall {
                arguments,
                location,
            } => {
                // For `base()`, we look up the parent class constructor.
                // At this point we don't know the parent class name, so we use "base"
                // as the registry key and fall back to positional if not found.
                let hir_args = self.build_call_args("base", arguments, location)?;

                Ok(HirExpression::BaseCall {
                    arguments: hir_args,
                    location: location.clone(),
                })
            }

            Expression::Range {
                start,
                end,
                inclusive,
                location,
            } => {
                let hir_start = self.build_expression(start)?;
                let hir_end = self.build_expression(end)?;

                Ok(HirExpression::Range {
                    start: Box::new(hir_start),
                    end: Box::new(hir_end),
                    step: None, // Expression::Range doesn't have step; it's in Statement::RangeIterate
                    inclusive: *inclusive,
                    location: location.clone(),
                })
            }

            Expression::ObjectLiteral { fields, location } => {
                let mut hir_fields = Vec::with_capacity(fields.len());
                for (key, value) in fields {
                    let hir_value = self.build_expression(value)?;
                    hir_fields.push((key.clone(), hir_value));
                }
                Ok(HirExpression::ObjectLiteral {
                    fields: hir_fields,
                    location: location.clone(),
                })
            }

            // `start expr` — async launch marker; strip the wrapper and build the inner call.
            // The async dispatch is handled at statement level (LaterAssignment / Background).
            Expression::StartExpression { expression, .. } => self.build_expression(expression),

            // NamedArgBinding is consumed entirely within build_call_args.
            // If we reach here it means the parser emitted a NamedArgBinding in a
            // position that is not a call argument list (e.g. a standalone expression).
            // Emit a clear semantic error rather than silently producing garbage code.
            Expression::NamedArgBinding {
                label, location, ..
            } => Err(CompilerError::semantic_error_with_code(
                format!(
                    "FUNC008: named argument `{}:` used outside of a function call argument list",
                    label
                ),
                Some(
                    "Named argument syntax `label: value` is only valid inside call parentheses"
                        .to_string(),
                ),
                Some(location.clone()),
                "FUNC008",
            )),

            Expression::StringInterpolation(parts) => {
                // Lower `"hello {x}"` to a left-folded string concatenation:
                //   "hello " + x.toString()
                //
                // **Why this needs its own arm**: the catch-all below converts
                // any unmatched expression into `HirExpression::Literal { Value::Void }`,
                // which means before this fix a string literal with interpolation
                // silently became an empty string at runtime — no compile error
                // even when the interpolated identifier was undefined. The Void
                // literal also bypassed the resolver entirely, so the user got
                // no diagnostic. That is dashboard fp 224922a73397
                // (SEM-INTERP-UNDEFINED). The fix: build a proper HIR expression
                // so the resolver visits each interpolated subexpression like any
                // other use, emitting SEM006/SEM007 for undefined identifiers in
                // exactly the same way it would for `print(undefined_x)`.
                //
                // Wrapping every interpolation in `.toString()` mirrors what the
                // user would write by hand and forces the unified-type concat
                // contract. Calling `.toString()` on a value that's already a
                // string is harmless (string has an identity `toString`); calling
                // it on a value that has no `toString` produces a clear SEM007
                // pointing at the interpolation site rather than silently dropping
                // the result.
                let loc = SourceLocation::default();
                if parts.is_empty() {
                    return Ok(HirExpression::Literal {
                        value: Value::String(String::new()),
                        location: loc,
                    });
                }

                let mut acc: Option<HirExpression> = None;
                for part in parts {
                    let piece = match part {
                        StringPart::Text(text) => HirExpression::Literal {
                            value: Value::String(text.clone()),
                            location: loc.clone(),
                        },
                        StringPart::Interpolation(inner_expr) => {
                            let inner_hir = self.build_expression(inner_expr)?;
                            HirExpression::MethodCall {
                                receiver: Box::new(inner_hir),
                                method: "toString".to_string(),
                                arguments: vec![],
                                location: loc.clone(),
                            }
                        }
                    };
                    acc = Some(match acc {
                        None => piece,
                        Some(prev) => HirExpression::BinaryOp {
                            left: Box::new(prev),
                            op: HirBinaryOp::Add,
                            right: Box::new(piece),
                            location: loc.clone(),
                        },
                    });
                }

                Ok(acc.expect("non-empty parts already produced acc above"))
            }

            // SEM001: an `OrmQuery` reaching the HIR builder means no plugin claimed
            // the `Model.<verb>:` pattern. The most common cause is a typo in the
            // verb name (`User.fnd:` instead of `User.find:`) or a verb that no
            // installed plugin handles. Surface this as a hard error instead of
            // silently lowering to void — see bug SILENT-DROP.
            Expression::OrmQuery {
                model,
                verb,
                location,
                ..
            } => Err(CompilerError::semantic_error_with_code(
                format!(
                    "SEM001: unknown ORM verb `{}.{}:` — no installed plugin handles this expression block",
                    model, verb
                ),
                Some(
                    "Check the verb spelling (e.g. `find`, `first`, `insert`, `insert_id`, \
                     `update`, `upsert`, `delete`, `count`, `exists`, `paginate`, `cursor`) \
                     and ensure the plugin that owns this verb is listed under `plugins:`."
                        .to_string(),
                ),
                Some(location.clone()),
                "SEM001",
            )),

            // For unsupported expressions we lower to a void literal rather than
            // erroring, because some upstream rewrites legitimately leave behind
            // transient nodes that are pruned later (e.g. PropertyAssignment is
            // consumed at the statement level for list.setFlags). Logged at trace
            // so the silent path is observable when debugging but doesn't pollute
            // normal compilation output.
            other => {
                tracing::trace!(
                    expression = ?std::mem::discriminant(other),
                    "HIR builder catch-all: lowering unrecognised expression to void"
                );
                Ok(HirExpression::Literal {
                    value: Value::Void,
                    location: SourceLocation::default(),
                })
            }
        }
    }

    /// Convert AST binary operator to HIR binary operator
    fn convert_binary_op(&self, op: &BinaryOperator) -> HirBinaryOp {
        match op {
            BinaryOperator::Add => HirBinaryOp::Add,
            BinaryOperator::Subtract => HirBinaryOp::Subtract,
            BinaryOperator::Multiply => HirBinaryOp::Multiply,
            BinaryOperator::Divide => HirBinaryOp::Divide,
            BinaryOperator::Modulo => HirBinaryOp::Modulo,
            BinaryOperator::Power => HirBinaryOp::Power,
            BinaryOperator::Equal => HirBinaryOp::Equal,
            BinaryOperator::NotEqual => HirBinaryOp::NotEqual,
            BinaryOperator::Less => HirBinaryOp::Less,
            BinaryOperator::Greater => HirBinaryOp::Greater,
            BinaryOperator::LessEqual => HirBinaryOp::LessEqual,
            BinaryOperator::GreaterEqual => HirBinaryOp::GreaterEqual,
            BinaryOperator::Is => HirBinaryOp::Is,
            BinaryOperator::Not => HirBinaryOp::IsNot,
            BinaryOperator::And => HirBinaryOp::And,
            BinaryOperator::Or => HirBinaryOp::Or,
            BinaryOperator::Default => HirBinaryOp::NullCoalesce,
        }
    }

    /// Convert AST unary operator to HIR unary operator
    fn convert_unary_op(&self, op: &UnaryOperator) -> HirUnaryOp {
        match op {
            UnaryOperator::Negate => HirUnaryOp::Negate,
            UnaryOperator::Not => HirUnaryOp::Not,
            UnaryOperator::RequiredAssert => HirUnaryOp::Required,
        }
    }

    fn value_to_hir_type(&self, value: &Value) -> HirType {
        match value {
            Value::Integer(_) => HirType::Integer,
            Value::Number(_) => HirType::Number,
            Value::String(_) => HirType::String,
            Value::Boolean(_) => HirType::Boolean,
            Value::Integer8(_) => HirType::Integer8,
            Value::Integer8u(_) => HirType::Integer8u,
            Value::Integer16(_) => HirType::Integer16,
            Value::Integer16u(_) => HirType::Integer16u,
            Value::Integer32(_) => HirType::Integer32,
            Value::Integer64(_) => HirType::Integer64,
            Value::Number32(_) => HirType::Number32,
            Value::Number64(_) => HirType::Number64,
            Value::List(elements) => {
                let element_type = if let Some(first) = elements.first() {
                    Box::new(self.value_to_hir_type(first))
                } else {
                    // Empty list - use Void as placeholder, will be inferred from context
                    Box::new(HirType::Void)
                };
                HirType::List(element_type)
            }
            Value::Matrix(_) => {
                // Matrix type will be inferred properly in type checker
                HirType::Matrix(Box::new(HirType::Number))
            }
            Value::Pairs(_) => {
                // Pairs type will be inferred properly in type checker
                HirType::Pairs(Box::new(HirType::Void), Box::new(HirType::Void))
            }
            Value::None | Value::Void => HirType::Void,
        }
    }

    /// Convert AST state block to HIR state block
    fn build_state_block(
        &mut self,
        state_block: &crate::ast::StateBlock,
    ) -> Result<HirStateBlock, CompilerError> {
        let declarations = state_block
            .declarations
            .iter()
            .map(|decl| self.build_state_declaration(decl))
            .collect::<Result<Vec<_>, _>>()?;

        let computed = state_block
            .computed
            .iter()
            .map(|comp| self.build_computed_declaration(comp))
            .collect::<Result<Vec<_>, _>>()?;

        // Convert rules from AST to HIR expressions
        let rules = if let Some(ref rules_block) = state_block.rules {
            rules_block
                .rules
                .iter()
                .map(|expr| self.build_expression(expr))
                .collect::<Result<Vec<_>, _>>()?
        } else {
            Vec::new()
        };

        let scope = match state_block.scope {
            crate::ast::StateScope::App => HirStateScope::App,
            crate::ast::StateScope::Screen => HirStateScope::Screen,
        };

        Ok(HirStateBlock {
            declarations,
            computed,
            rules,
            scope,
            location: state_block.location.clone().unwrap_or_default(),
        })
    }

    /// Convert AST state declaration to HIR state declaration
    fn build_state_declaration(
        &mut self,
        decl: &crate::ast::StateDeclaration,
    ) -> Result<HirStateDeclaration, CompilerError> {
        let state_type = self.build_type(&decl.type_)?;
        let initializer = self.build_expression(&decl.initializer)?;

        let guard = if let Some(ast_guard) = &decl.guard {
            Some(HirGuardClause {
                condition: self.build_expression(&ast_guard.condition)?,
                error_message: ast_guard.error_message.clone(),
                location: ast_guard.location.clone().unwrap_or_default(),
            })
        } else {
            None
        };

        Ok(HirStateDeclaration {
            name: decl.name.clone(),
            state_type,
            initializer,
            guard,
            is_private: decl.is_private,
            location: decl.location.clone().unwrap_or_default(),
        })
    }

    /// Convert AST computed declaration to HIR computed declaration
    fn build_computed_declaration(
        &mut self,
        comp: &crate::ast::ComputedDeclaration,
    ) -> Result<HirComputedDeclaration, CompilerError> {
        let computed_type = self.build_type(&comp.type_)?;
        let body = self.build_block(&comp.body)?;

        Ok(HirComputedDeclaration {
            name: comp.name.clone(),
            computed_type,
            body,
            location: comp.location.clone().unwrap_or_default(),
        })
    }

    /// Convert AST watch block to HIR watch block
    fn build_watch_block(
        &mut self,
        watch: &crate::ast::WatchBlock,
    ) -> Result<HirWatchBlock, CompilerError> {
        let body = self.build_block(&watch.body)?;

        Ok(HirWatchBlock {
            targets: watch.targets.clone(),
            body,
            location: watch.location.clone().unwrap_or_default(),
        })
    }

    // =========================================================================
    // Validate block desugaring
    //
    // `validate name:` is syntactic sugar for a sequence of `validator.*` calls
    // that build up a ValidationRules object. We desugar directly in the HIR
    // builder so that the rest of the pipeline sees only ordinary Call nodes.
    //
    // The desugaring for a schema named `foo` with two fields looks like:
    //
    //   foo = validator.createWithName("foo")
    //   foo = validator.field(foo, "name")
    //   foo = validator.required(foo, 1)
    //   foo = validator.minLength(foo, 1)
    //   foo = validator.maxLength(foo, 50)
    //   foo = validator.field(foo, "email")
    //   foo = validator.required(foo, 1)
    //   foo = validator.match(foo, "email")
    //   foo = validator.message(foo, "Please enter a valid email address")
    //   foo = validator.message(foo, "Please check this field")   // default
    //
    // `schemaName.check expr:` desugars to:
    //
    //   __result = validator.run(schemaName, expr)
    //   if validator.isOk(__result):
    //       value = validator.getValue(__result)
    //       <ok_branch>
    //   else:
    //       errors = validator.getErrors(__result)
    //       <error_branch>
    // =========================================================================

    // =========================================================================
    // String-accumulator-loop rewrite (CMP-SSR-MALLOC-OOM-PAGE-RENDER)
    //
    // Detects:
    //     string acc = ""
    //     while <cond>             // or `for` over a range
    //         …
    //         acc = acc + <expr>   // exactly one self-append, anywhere in body
    //         …
    //
    // and rewrites it to:
    //
    //     integer __sb_N = string_builder_new()
    //     while <cond>
    //         …
    //         __sb_N = string_builder_append(__sb_N, <expr>)
    //         …
    //     string acc = string_builder_finalize(__sb_N)
    //
    // Disqualifiers (any one falls back to the slow path):
    //   - The initializer isn't a literal "" empty string.
    //   - `acc` is read anywhere in the loop body other than as the LHS of the
    //     unique self-append (e.g. `print(acc)`, `acc.length()`, `other = acc`).
    //   - `acc` is written anywhere else in the body.
    //   - The body contains an early `return` (would observe partial state).
    //   - The body contains a `LaterAssignment` or `Background` (suspension
    //     points could observe `acc`).
    //   - The body contains a `break` (would leave the builder unfinalized
    //     in a way that exposes `acc` mid-flight).
    //   - `acc = expr + acc` (prepend) — design is append-only.
    //
    // The rewrite is bottom-up because `build_block` runs this pass at the
    // tail of every recursive call, so nested accumulator loops are
    // rewritten before their enclosing ones.
    // =========================================================================

    /// Walk the block's statements looking for `string acc = ""` declarations
    /// and a downstream loop that uses `acc` in the accumulator pattern.
    /// Rewrite each match in place.
    ///
    /// Adjacency rule: the decl does NOT have to be immediately before the
    /// loop. The original sketch required strict adjacency, but the
    /// canonical SSR repro intersperses an `integer i = 0` between
    /// `string acc = ""` and `while`, so strict adjacency would never
    /// fire on the very pattern the rewrite exists to handle. We instead
    /// scan forward from each candidate decl, verifying no intervening
    /// statement reads or writes `acc`, until we hit either:
    ///   - a matching loop (rewrite),
    ///   - a statement that observes `acc` (give up on this decl),
    ///   - the end of the block (give up).
    fn rewrite_string_accumulator_loops(&mut self, stmts: &mut Vec<HirStatement>) {
        let mut i = 0;
        while i + 1 < stmts.len() {
            // Quick filter: this position must hold `string <name> = ""`.
            let Some(acc_name) = Self::accumulator_decl_name(&stmts[i]) else {
                i += 1;
                continue;
            };

            // Scan forward for the loop that consumes this accumulator,
            // bailing if any intervening statement touches `acc`.
            let mut scan = i + 1;
            let mut matched_loop_idx: Option<usize> = None;
            while scan < stmts.len() {
                if Self::stmt_is_accumulator_loop(&stmts[scan], &acc_name) {
                    matched_loop_idx = Some(scan);
                    break;
                }
                // Intervening statement — verify it doesn't touch `acc`.
                let mut probe = AccumulatorAnalysis::default();
                Self::analyze_stmt_for_accumulator(&stmts[scan], &acc_name, &mut probe);
                if probe.disqualified || probe.reads > 0 || probe.self_appends > 0 {
                    break;
                }
                scan += 1;
            }

            let Some(loop_idx) = matched_loop_idx else {
                i += 1;
                continue;
            };

            // Pattern is committed; clone the decl + loop, run the
            // full rewrite, splice the result back in.
            let decl_clone = stmts[i].clone();
            let loop_clone = stmts[loop_idx].clone();
            let Some(rewrite) = self.try_match_accumulator_pair(&decl_clone, &loop_clone) else {
                i += 1;
                continue;
            };

            // Splice the rewrite:
            //   - replace decl at i with decl_replacement,
            //   - optionally insert mark_decl at i + 1 (captures HEAP_PTR
            //     right after the builder is constructed; only emitted
            //     when the body is reclaim-safe and a reclaim call is
            //     also emitted into the body),
            //   - replace the (now-shifted) loop at loop_idx + 1 with
            //     replacement_loop,
            //   - insert finalize_decl after the loop.
            stmts[i] = rewrite.decl_replacement;
            let mut shifted_loop_idx = loop_idx;
            if let Some(mark_decl) = rewrite.mark_decl {
                stmts.insert(i + 1, mark_decl);
                shifted_loop_idx = loop_idx + 1;
            }
            stmts[shifted_loop_idx] = rewrite.replacement_loop;
            stmts.insert(shifted_loop_idx + 1, rewrite.finalize_decl);

            // Resume scanning after the newly inserted finalize.
            i = shifted_loop_idx + 2;
        }
    }

    /// Single-shot (loop-free) accumulator rewrite. Catches the pattern
    ///
    ///   string acc = ""
    ///   acc = acc + e1 + e2 + ... + eN     [+ further chained appends]
    ///   <any non-write use of acc, or end of block>
    ///
    /// and rewrites it to
    ///
    ///   string __sb_M = string_builder_new()
    ///   __sb_M = string_builder_append(__sb_M, e1)
    ///   __sb_M = string_builder_append(__sb_M, e2)
    ///   ...
    ///   __sb_M = string_builder_append(__sb_M, eN)
    ///   string acc = string_builder_finalize(__sb_M)
    ///   <any non-write use of acc — unchanged because `acc` is rebound
    ///    by the finalize, so downstream readers see a normal string>
    ///
    /// This mirrors what javac/Kotlin/Go do for chained concatenation
    /// outside loops: turn N+1 separate allocations (N concat results,
    /// each stranded on the bump heap, plus the final acc) into one
    /// builder + N appends + one finalize.
    ///
    /// Why a separate pass from `rewrite_string_accumulator_loops`:
    /// the loop matcher requires a `while`/`for` to follow the decl
    /// and runs `try_match_accumulator_pair` which does loop-specific
    /// work (transient-scope wrap, conditional-helper routing). The
    /// single-shot case has none of that — no scope, no helpers, just
    /// a linear sequence of statements producing the final string. We
    /// deliberately do NOT thread the transient arena into this path:
    /// the StringBuilder lives in the function's frame and gets
    /// finalized into a normal __malloc-allocated string before any
    /// caller sees it. The intermediate fragments (`e1..eN`) are local
    /// temporaries the host reclaims on per-request `scope_pop`.
    ///
    /// Plugin emission shape this catches (canonical case for the
    /// outstanding /syntax + /tutorials OOM as of v0.30.378):
    /// `frame.ui` 2.12.x's expand_html_block emits exactly the
    /// chained-RHS shape above for every html: block, and the helpers
    /// it wraps (renderCard, tutorialCard, renderCodeWindow, etc.) get
    /// called from inside SSR loops in the page file. The single-shot
    /// rewrite turns each helper call from ~20 stranded main-heap
    /// allocations into 1.
    fn rewrite_string_accumulator_singleshot(&mut self, stmts: &mut Vec<HirStatement>) {
        let mut i = 0;
        while i + 1 < stmts.len() {
            // Quick filter: this position must hold `string <name> = ""`.
            let Some(acc_name) = Self::accumulator_decl_name(&stmts[i]) else {
                i += 1;
                continue;
            };

            // Scan forward collecting consecutive chained-RHS self-appends.
            // Stop at the first statement that is NOT a self-append (a tail
            // use of `acc` is allowed but does not extend the chain).
            //
            // An intervening statement that reads `acc` outside the LHS slot
            // disqualifies the match — the rewrite invariant requires that
            // `acc` is never observed in its intermediate (pre-finalize)
            // shape, because between the new `__sb_M` decl and the inserted
            // `string acc = string_builder_finalize(__sb_M)` there is no
            // binding named `acc` at all.
            let mut last_append_idx: Option<usize> = None;
            let mut scan = i + 1;
            let mut window_disqualified = false;
            while scan < stmts.len() {
                if Self::stmt_is_chained_self_append(&stmts[scan], &acc_name) {
                    last_append_idx = Some(scan);
                    scan += 1;
                    continue;
                }
                // Not a self-append. Check that it doesn't write `acc`
                // in a disqualifying way. Reads, returns, and other
                // statements are allowed here — they just stop the
                // append window.
                //
                // NOTE: We deliberately do NOT use the full
                // `analyze_stmt_for_accumulator` here — that analyzer
                // treats `return acc` as a disqualifying "early return"
                // because it was designed for the loop case. In the
                // single-shot case, `return acc` is the canonical tail
                // use (every plugin-emitted html: block ends with
                // `return __html`) and must be allowed. The
                // `stmt_writes_acc` predicate only checks for writes.
                if Self::stmt_writes_acc(&stmts[scan], &acc_name) {
                    window_disqualified = true;
                    break;
                }
                // Tail use: end the append window, continue to tail-check.
                break;
            }

            let Some(last_append) = last_append_idx else {
                i += 1;
                continue;
            };

            if window_disqualified {
                i = scan + 1;
                continue;
            }

            // Now verify the rest of the block (after the last append) does
            // not contain a non-canonical write to `acc`. Tail reads are
            // fine (they see the post-finalize string). Tail writes would
            // observe the pre-rewrite shape and break.
            //
            // The rewrite inserts `string acc = string_builder_finalize(__sb)`
            // right after the appends, so all downstream readers see a
            // normal string. We disqualify only on tail writes to `acc`
            // that are not themselves chained-self-appends.
            let mut tail_write_violation = false;
            for stmt in &stmts[last_append + 1..] {
                if Self::stmt_writes_acc(stmt, &acc_name) {
                    tail_write_violation = true;
                    break;
                }
            }
            if tail_write_violation {
                i += 1;
                continue;
            }

            // Commit. Allocate a fresh builder name.
            let sb_name = format!("__sb_{}", self.string_builder_counter);
            self.string_builder_counter += 1;
            let decl_loc = match &stmts[i] {
                HirStatement::VariableDeclaration { location, .. } => location.clone(),
                _ => {
                    unreachable!("accumulator_decl_name pre-validated this is VariableDeclaration")
                }
            };

            // Build the replacement statements:
            //   - decl_replacement: `string __sb_M = string_builder_new()`
            //   - flattened appends:   one statement per fragment, replacing
            //                          the N chained self-append statements
            //   - finalize_decl:    `string acc = string_builder_finalize(__sb_M)`
            //                       inserted after the last append
            let decl_replacement = HirStatement::VariableDeclaration {
                name: sb_name.clone(),
                var_type: HirType::String,
                initializer: Some(HirExpression::Call {
                    function: "string_builder_new".to_string(),
                    arguments: vec![],
                    location: decl_loc.clone(),
                }),
                is_mutable: true,
                location: decl_loc.clone(),
            };
            let finalize_decl = HirStatement::VariableDeclaration {
                name: acc_name.clone(),
                var_type: HirType::String,
                initializer: Some(HirExpression::Call {
                    function: "string_builder_finalize".to_string(),
                    arguments: vec![HirExpression::Variable {
                        name: sb_name.clone(),
                        location: decl_loc.clone(),
                    }],
                    location: decl_loc.clone(),
                }),
                is_mutable: true,
                location: decl_loc.clone(),
            };

            // Drain the chained self-append window (i+1..=last_append) and
            // flatten each into per-fragment `__sb = string_builder_append(__sb, eK)`
            // statements via the existing `rewrite_self_append_collect` machinery.
            let mut flattened_appends: Vec<HirStatement> = Vec::new();
            let drained: Vec<HirStatement> = stmts.drain(i + 1..=last_append).collect();
            for stmt in drained {
                Self::rewrite_self_append_collect(
                    stmt,
                    &acc_name,
                    &sb_name,
                    &mut flattened_appends,
                );
            }

            // Splice in the rewrite output:
            //   - replace stmts[i] with decl_replacement
            //   - insert flattened_appends + finalize_decl right after it
            stmts[i] = decl_replacement;
            let mut to_insert = flattened_appends;
            to_insert.push(finalize_decl);
            let new_segment_len = to_insert.len();
            stmts.splice(i + 1..i + 1, to_insert);
            // Resume scanning after the newly inserted finalize.
            // i (decl) + 1 + new_segment_len (appends + finalize) = next index
            i = i + 1 + new_segment_len;
        }
    }

    /// True iff `stmt` is `acc = acc + e1 + e2 + ... + eN` (a chained
    /// self-append on `acc_name`). Mirrors the predicate used inside
    /// `analyze_stmt_for_accumulator`, exposed as a top-level filter for
    /// the single-shot matcher's window scan.
    fn stmt_is_chained_self_append(stmt: &HirStatement, acc_name: &str) -> bool {
        match stmt {
            HirStatement::Assignment {
                target: HirLValue::Variable { name, .. },
                value,
                ..
            } if name == acc_name => Self::is_chained_self_append(value, acc_name),
            _ => false,
        }
    }

    /// True iff `stmt` (or any nested statement inside it) writes the
    /// variable named `acc_name`. Used by the single-shot matcher to
    /// reject tail statements that would re-assign the accumulator
    /// after the chained-RHS window closes — those would observe the
    /// pre-rewrite shape and break.
    ///
    /// Reads of `acc_name` are NOT rejected: the rewrite inserts a
    /// `string acc = string_builder_finalize(__sb)` right after the
    /// last append, so all downstream readers see a normal post-rewrite
    /// string with the original name. `return acc`, `printl(acc)`,
    /// `someFunc(acc)` etc. are all safe tail uses.
    fn stmt_writes_acc(stmt: &HirStatement, acc_name: &str) -> bool {
        match stmt {
            HirStatement::Assignment {
                target: HirLValue::Variable { name, .. },
                ..
            } => name == acc_name,
            HirStatement::VariableDeclaration { name, .. } if name == acc_name => {
                // Shadowing inside an inner scope (e.g. an `if` branch)
                // would not reach here because nested statements are
                // wrapped in If/While/For. A top-level redecl of `acc`
                // would mean two `string acc = ...` decls in the same
                // block — illegal in Clean, but treat as a write to be
                // safe.
                true
            }
            HirStatement::If {
                then_branch,
                else_branch,
                ..
            } => {
                if then_branch
                    .statements
                    .iter()
                    .any(|s| Self::stmt_writes_acc(s, acc_name))
                {
                    return true;
                }
                if let Some(eb) = else_branch {
                    if eb
                        .statements
                        .iter()
                        .any(|s| Self::stmt_writes_acc(s, acc_name))
                    {
                        return true;
                    }
                }
                false
            }
            HirStatement::While { body, .. } | HirStatement::For { body, .. } => body
                .statements
                .iter()
                .any(|s| Self::stmt_writes_acc(s, acc_name)),
            _ => false,
        }
    }

    /// Cheap filter: is this statement `string <name> = ""`?
    /// Returns the variable name when it matches, `None` otherwise.
    fn accumulator_decl_name(stmt: &HirStatement) -> Option<String> {
        let HirStatement::VariableDeclaration {
            name,
            var_type,
            initializer,
            ..
        } = stmt
        else {
            return None;
        };
        if !matches!(var_type, HirType::String) {
            return None;
        }
        match initializer {
            Some(HirExpression::Literal {
                value: Value::String(s),
                ..
            }) if s.is_empty() => Some(name.clone()),
            _ => None,
        }
    }

    /// Is this statement a `while`/`for` whose body contains the canonical
    /// self-append on `acc_name` (and is otherwise rewrite-safe)?
    /// Used as the candidate-loop predicate while scanning forward from a
    /// matched decl.
    fn stmt_is_accumulator_loop(stmt: &HirStatement, acc_name: &str) -> bool {
        let body = match stmt {
            HirStatement::While { body, .. } | HirStatement::For { body, .. } => body,
            _ => return false,
        };
        let mut analysis = AccumulatorAnalysis::default();
        Self::analyze_block_for_accumulator(body, acc_name, &mut analysis);
        analysis.is_rewritable()
    }

    /// If `(decl, loop_stmt)` matches the accumulator pattern, mutate the
    /// loop body in place (replacing the self-append) and return the
    /// replacement declarations. Returns `None` otherwise (and leaves the
    /// loop body untouched).
    fn try_match_accumulator_pair(
        &mut self,
        decl: &HirStatement,
        loop_stmt: &HirStatement,
    ) -> Option<AccumulatorRewrite> {
        // -- Step 1: decl must be `string <name> = ""`.
        let (acc_name, decl_loc) = match decl {
            HirStatement::VariableDeclaration {
                name,
                var_type,
                initializer,
                location,
                ..
            } => {
                if !matches!(var_type, HirType::String) {
                    return None;
                }
                match initializer {
                    Some(HirExpression::Literal {
                        value: Value::String(s),
                        ..
                    }) if s.is_empty() => (name.clone(), location.clone()),
                    _ => return None,
                }
            }
            _ => return None,
        };

        // -- Step 2: loop_stmt must be a While or For; clone its body so we
        // can decide whether to commit before mutating the caller's slice.
        let (mut new_body, loop_kind) = match loop_stmt {
            HirStatement::While { body, .. } => (body.clone(), LoopKind::While),
            HirStatement::For { body, .. } => (body.clone(), LoopKind::For),
            _ => return None,
        };

        // -- Step 3: scan the body for exactly one canonical self-append and
        // verify `acc` is not touched anywhere else.
        let mut analysis = AccumulatorAnalysis::default();
        Self::analyze_block_for_accumulator(&new_body, &acc_name, &mut analysis);
        if !analysis.is_rewritable() {
            return None;
        }

        // -- Step 4: commit. Allocate a fresh builder name and mutate the
        // body in place, replacing the self-append.
        let sb_name = format!("__sb_{}", self.string_builder_counter);
        let mark_name = format!("__sb_{}_mark", self.string_builder_counter);
        let tmark_name = format!("__sb_{}_tmark", self.string_builder_counter);
        self.string_builder_counter += 1;

        Self::rewrite_self_append_in_block(&mut new_body, &acc_name, &sb_name);

        // Step 4a-pre: route body-local string-concat results through the
        // transient arena. After `rewrite_self_append_in_block` has
        // converted the accumulator's self-append into
        // `string_builder_append` calls, the remaining `BinaryOp::Add`
        // chains in the body are conditional helpers like
        //   string headHtml = ""
        //   if head != ""
        //       headHtml = "<h2>" + head + "</h2>"
        // The `headHtml` LHS is declared inside the body (we verified
        // this via `collect_body_local_string_names`) so its concat
        // result's lifetime is bounded by the iteration. Rewriting the
        // chain to `string_concat_transient` calls lands the result in
        // the transient pool, which is reset at end-of-iter by the
        // `__transient_scope_exit` appended below.
        //
        // Names declared OUTSIDE the loop (the canonical
        // `head = json.get(...)` shape that broke
        // CMP-SSR-RECLAIM-FREES-LIVE-POINTER) are NOT in the body-local
        // set and are NOT rewritten. Their concat results continue to
        // allocate via `__malloc`, live on the main heap, and survive
        // the per-iter transient reset. That's the Cyclone region
        // invariant that makes this routing safe where end-of-body
        // reclaim was not.
        let mut body_local_string_names = std::collections::HashSet::new();
        Self::collect_body_local_string_names(&new_body, &mut body_local_string_names);
        Self::rewrite_body_local_helpers_to_transient(&mut new_body, &body_local_string_names);

        // Step 4a: the per-iter `string_builder_reclaim(__sb_N, __mark_N)`
        // mechanism stays disabled.
        //
        // The end-of-body reclaim added in 0.30.373 corrupts any
        // cross-iter live pointer above the post-reclaim HEAP_PTR —
        // surfaced as CMP-SSR-RECLAIM-FREES-LIVE-POINTER (7fc4f890aab9...)
        // within hours of 0.30.374 shipping. The rollback in 0.30.375
        // removed the emission. The reclaim helper stays registered
        // (it's harmless if uncalled) so re-enabling is a single-line
        // change once full body-escape tracking lands.
        //
        // The replacement mechanism is a Cyclone-style nested region:
        // outer-scope values stay on the main heap, per-iteration
        // intermediates flow through a separate transient pool. Step
        // 4a' below wraps the body in `__transient_scope_enter` /
        // `__transient_scope_exit`. Routing intra-body string.concat
        // results through `__transient_alloc` happens in a follow-up
        // commit — this revision only sets up the scope so that
        // routing can be enabled incrementally without re-introducing
        // the dangling-pointer failure mode.
        let _ = &mark_name; // mark_name reserved for the future re-enable.

        // Step 4a': wrap the body with transient-arena enter / exit.
        //
        //   __sb_N_tmark = __transient_scope_enter()
        //   <body>
        //   __transient_scope_exit(__sb_N_tmark)
        //
        // `__transient_scope_enter` returns the current transient bump
        // pointer (the save mark). Lazy-init of the pool happens inside
        // the helper on first call. `__transient_scope_exit` writes
        // that mark back, releasing every allocation made via
        // `__transient_alloc` during the iteration without touching the
        // main heap. Because outer-scope assignments (the
        // `head = json.get(...)` shape from CMP-SSR-RECLAIM-FREES-LIVE-
        // POINTER) continue to use `__malloc`, they live on the main
        // heap and are *not* in the region that gets reset — the
        // failure mode that motivated the reclaim rollback cannot
        // recur from this scope mechanism alone.
        //
        // Until Step 3 wires `string.concat` routing into the
        // transient pool, this enter/exit pair is a no-op: the helper
        // is registered, the scope is established, but no allocations
        // currently route through it. Shipping the scope first lets
        // us validate the bookkeeping in isolation before turning on
        // the routing.
        let tmark_init = HirExpression::Call {
            function: "transient_scope_enter".to_string(),
            arguments: vec![],
            location: decl_loc.clone(),
        };
        let tmark_decl = HirStatement::VariableDeclaration {
            name: tmark_name.clone(),
            var_type: HirType::Integer,
            initializer: Some(tmark_init),
            is_mutable: false,
            location: decl_loc.clone(),
        };
        let tmark_exit = HirStatement::Expression {
            expression: HirExpression::Call {
                function: "transient_scope_exit".to_string(),
                arguments: vec![HirExpression::Variable {
                    name: tmark_name.clone(),
                    location: decl_loc.clone(),
                }],
                location: decl_loc.clone(),
            },
            location: decl_loc.clone(),
        };
        new_body.statements.insert(0, tmark_decl);
        new_body.statements.push(tmark_exit);

        // Stitch the (now-rewritten) body back into the loop statement.
        let new_loop = match loop_stmt {
            HirStatement::While {
                condition,
                location,
                ..
            } => HirStatement::While {
                condition: condition.clone(),
                body: new_body,
                location: location.clone(),
            },
            HirStatement::For {
                variable,
                iterable,
                location,
                ..
            } => HirStatement::For {
                variable: variable.clone(),
                iterable: iterable.clone(),
                body: new_body,
                location: location.clone(),
            },
            _ => unreachable!("loop_kind matched above"),
        };
        let _ = loop_kind; // kept for clarity; both arms produce the right variant.

        // Step 4b: emit the builder-init decl. At the WASM level the
        // builder handle is an i32 pointer, but we declare it as
        // `String` so the MIR-level `body_is_iter_scope_safe` predicate
        // sees writes to `__sb_N` from inside the loop body as an
        // outer-scope assignment of an arena-allocated type — which
        // suppresses the per-iteration `mem_scope_push` / `mem_scope_pop`
        // pair. Without that suppression, scope_pop reclaims the heap
        // region the builder lives in and the next iter's appends
        // overwrite it. The String shape is purely a marker; the WASM
        // representation (i32 ptr) is unchanged. Per-iter reclamation
        // is handled selectively by the explicit `string_builder_reclaim`
        // call appended to the body above.
        let decl_replacement = HirStatement::VariableDeclaration {
            name: sb_name.clone(),
            var_type: HirType::String,
            initializer: Some(HirExpression::Call {
                function: "string_builder_new".to_string(),
                arguments: vec![],
                location: decl_loc.clone(),
            }),
            is_mutable: true,
            location: decl_loc.clone(),
        };

        // Step 4b': capture HEAP_PTR right after the builder is built.
        // This becomes the `init_mark` argument to every per-iter
        // `string_builder_reclaim` call. Only emitted when the body is
        // reclaim-safe and the rewrite ALSO appended a reclaim call
        // (Step 4a). When the rewrite skipped reclaim emission (e.g.
        // body escapes — CMP-SSR-RECLAIM-FREES-LIVE-POINTER), the mark
        // is not needed and we return `None` to avoid an unused integer
        // local.
        let mark_decl = None;

        // Step 4c: emit the post-loop finalize decl. This re-binds the
        // original `acc` name to a real Clean string for any downstream
        // reader. The original decl was `is_mutable: true` by spec for
        // assignments to work; we preserve that.
        let finalize_decl = HirStatement::VariableDeclaration {
            name: acc_name.clone(),
            var_type: HirType::String,
            initializer: Some(HirExpression::Call {
                function: "string_builder_finalize".to_string(),
                arguments: vec![HirExpression::Variable {
                    name: sb_name.clone(),
                    location: decl_loc.clone(),
                }],
                location: decl_loc.clone(),
            }),
            is_mutable: true,
            location: decl_loc.clone(),
        };

        // Note: the *loop* in the caller's slice is still the original
        // statement at `stmts[i+1]`. We need to overwrite it. Return the
        // replacement loop in a side channel.
        Some(AccumulatorRewrite {
            decl_replacement,
            mark_decl,
            finalize_decl,
            replacement_loop: new_loop,
        })
    }

    // =========================================================================
    // Dual-accumulator-loop rewrite (COMPILER-MEM-ALLOC-NO-GROW-RECURRENCE,
    // fingerprint b80c2f907c71)
    //
    // Detects the `expand_endpoints` shape:
    //
    //   string A = <literal>    // may be non-empty (e.g. "functions:\n")
    //   string B = ""           // or any literal
    //   while <cond>
    //       ... body with multiple `A = A + <chain>` and `B = B + <chain>` ...
    //
    // and rewrites EACH ITERATION to:
    //
    //   while <cond>
    //       integer __da_N_atmark = _arena_scope_push()
    //       ... body with `A = A + <chain>` and `B = B + <chain>` intact ...
    //       _arena_scope_pop(__da_N_atmark)
    //
    // The CRITICAL difference from the single-accumulator rewrite: the final
    // `A = A + chunk` and `B = B + chunk` assignments in each branch stay
    // in place but are moved BEFORE the _arena_scope_pop. The pop reclaims
    // only the per-iteration intermediates (substrings, helper strings) that
    // accumulate on the host arena between the push and the pop.
    //
    // Wait — that's incorrect. If `A = A + chunk` is inside the scope, the
    // new `A` pointer (allocated by `string.concat`) is in the scope region
    // and gets reclaimed by the pop. The CORRECT shape is:
    //
    //   __da_N_atmark = _arena_scope_push()
    //   ... body, EXCEPT the outer-scope self-appends on A and B ...
    //   ... replace each `A = A + <chain>` with a local:
    //       string __da_N_chunkA = <chain>   (just the chain, not prefixed with A)
    //   ... replace each `B = B + <chain>` with a local:
    //       string __da_N_chunkB = <chain>
    //   _arena_scope_pop(__da_N_atmark)
    //   A = A + __da_N_chunkA
    //   B = B + __da_N_chunkB
    //
    // The chunk locals land IN the scope region and get reclaimed on pop;
    // the final `A + chunk_A` concat lands OUTSIDE the scope region and
    // survives. This matches the design doc §3.3.2 invariant.
    //
    // SIMPLIFICATION for robustness: rather than trying to split each
    // conditional branch's multiple appends into a single chunk per branch,
    // we only fire when the loop body has AT MOST one `A = A + chain` path
    // and AT MOST one `B = B + chain` path through any given if/else branch
    // (the "flat body" predicate). This avoids the thorny multi-append
    // coalescing needed for the LIVE branch's 3+ result appends. The
    // flat-body predicate conservatively rejects bodies that don't meet
    // this criterion, leaving them on the slow path. That's acceptable for
    // now — the dominant OOM cause is the triangular sum across N iterations,
    // not within one iteration.
    //
    // Disqualifiers:
    //   - The body contains early `return` or suspension points.
    //   - Either accumulator has reads outside the canonical self-append.
    //   - The total self-append count for either accumulator is > 1 when
    //     considering all branches jointly (conservative flat-body check).
    //   - The single-accumulator rewrite already fired on one of the decls
    //     (i.e. the decl was replaced by `string_builder_new`; we'd detect
    //     this via the function name in the initializer — but we simply
    //     verify `accumulator_decl_name` still returns the name, which fails
    //     on already-rewritten decls).
    //
    // This rewrite DOES NOT use string_builder_new/append/finalize. It only
    // injects _arena_scope_push/_arena_scope_pop calls. The accumulators
    // stay as ordinary strings — the push/pop just reduces the host arena
    // pressure by reclaiming per-iteration intermediates before the next
    // iteration allocates its own batch.
    // =========================================================================

    /// Walk the block's statements looking for two `string A = <lit>` and
    /// `string B = <lit>` declarations (possibly with non-string intervening
    /// statements) followed by a loop that appends to BOTH accumulators.
    /// Rewrite the loop body to bracket each iteration with host arena
    /// scope push/pop so per-iteration intermediate strings are reclaimed.
    ///
    /// The second accumulator decl does NOT need to be immediately after the
    /// first — it can have up to `MAX_DUAL_ACC_SCAN` intervening statements
    /// that don't touch either accumulator. This mirrors the single-accumulator
    /// detector's forward-scan policy.
    fn rewrite_dual_accumulator_loops(&mut self, stmts: &mut Vec<HirStatement>) {
        // Maximum number of intervening statements to scan over when looking
        // for the second accumulator decl or the loop.
        const MAX_DUAL_ACC_SCAN: usize = 16;

        let mut i = 0;
        while i + 2 < stmts.len() {
            // Quick filter: position i must hold `string <nameA> = <literal>`.
            let Some(name_a) = Self::accumulator_decl_name_any_literal(&stmts[i]) else {
                i += 1;
                continue;
            };

            // Scan forward from i+1 for `string <nameB> = <literal>` (a
            // different name) with at most MAX_DUAL_ACC_SCAN intervening
            // statements that don't touch name_a.
            let mut name_b: Option<String> = None;
            let mut scan_b = i + 1;
            let mut scan_limit = scan_b + MAX_DUAL_ACC_SCAN;
            while scan_b < stmts.len().min(scan_limit) {
                if let Some(cand_b) = Self::accumulator_decl_name_any_literal(&stmts[scan_b]) {
                    if cand_b != name_a {
                        name_b = Some(cand_b);
                        break;
                    }
                }
                // Intervening statement — bail if it touches name_a.
                let mut probe = AccumulatorAnalysis::default();
                Self::analyze_stmt_for_accumulator(&stmts[scan_b], &name_a, &mut probe);
                if probe.disqualified || probe.reads > 0 || probe.self_appends > 0 {
                    break;
                }
                scan_b += 1;
            }
            let Some(name_b) = name_b else {
                i += 1;
                continue;
            };

            // Scan forward from scan_b+1 for a loop that appends to BOTH A and B.
            let mut scan_loop = scan_b + 1;
            scan_limit = scan_loop + MAX_DUAL_ACC_SCAN;
            let mut matched_loop_idx: Option<usize> = None;
            while scan_loop < stmts.len().min(scan_limit) {
                if Self::stmt_is_dual_accumulator_loop(&stmts[scan_loop], &name_a, &name_b) {
                    matched_loop_idx = Some(scan_loop);
                    break;
                }
                // Intervening statement — verify it doesn't touch either acc.
                let mut probe_a = AccumulatorAnalysis::default();
                let mut probe_b = AccumulatorAnalysis::default();
                Self::analyze_stmt_for_accumulator(&stmts[scan_loop], &name_a, &mut probe_a);
                Self::analyze_stmt_for_accumulator(&stmts[scan_loop], &name_b, &mut probe_b);
                if probe_a.disqualified
                    || probe_a.reads > 0
                    || probe_a.self_appends > 0
                    || probe_b.disqualified
                    || probe_b.reads > 0
                    || probe_b.self_appends > 0
                {
                    break;
                }
                scan_loop += 1;
            }

            let Some(loop_idx) = matched_loop_idx else {
                i += 1;
                continue;
            };

            // Commit to the rewrite.
            let loop_clone = stmts[loop_idx].clone();
            let decl_a_loc: SourceLocation = match &stmts[i] {
                HirStatement::VariableDeclaration { location, .. } => location.clone(),
                _ => unreachable!(),
            };
            let Some(rewritten_loop) =
                self.try_rewrite_dual_accumulator_loop(&loop_clone, &name_a, &name_b, &decl_a_loc)
            else {
                i += 1;
                continue;
            };

            stmts[loop_idx] = rewritten_loop;
            // Resume scanning after the rewritten loop.
            i = loop_idx + 1;
        }
    }

    /// Variant of `accumulator_decl_name` that accepts ANY string literal
    /// as the initializer, not just the empty string. Needed because
    /// `result` is initialized to `"functions:\n"` in `expand_endpoints`.
    fn accumulator_decl_name_any_literal(stmt: &HirStatement) -> Option<String> {
        let HirStatement::VariableDeclaration {
            name,
            var_type,
            initializer,
            ..
        } = stmt
        else {
            return None;
        };
        if !matches!(var_type, HirType::String) {
            return None;
        }
        match initializer {
            Some(HirExpression::Literal {
                value: Value::String(_),
                ..
            }) => Some(name.clone()),
            _ => None,
        }
    }

    /// Returns true when `stmt` is a while/for loop whose body:
    ///   - contains at least one self-append on `name_a` AND one on `name_b`
    ///   - has no disqualifiers (early return, suspension, etc.)
    ///   - neither accumulator is read outside the LHS of a self-append
    ///   - the per-branch append count for each accumulator is <= 1
    ///     (conservative flat-body predicate)
    fn stmt_is_dual_accumulator_loop(stmt: &HirStatement, name_a: &str, name_b: &str) -> bool {
        let body = match stmt {
            HirStatement::While { body, .. } | HirStatement::For { body, .. } => body,
            _ => return false,
        };

        let mut analysis_a = AccumulatorAnalysis::default();
        let mut analysis_b = AccumulatorAnalysis::default();

        // We use the existing single-accumulator block analysis for each
        // accumulator independently. For the dual case both must be
        // individually rewritable, with the relaxation that `self_appends`
        // may be > 1 (one per conditional branch) — so we DON'T call
        // `is_rewritable()` which requires exactly 1 self_append.
        Self::analyze_block_for_dual_accumulator(body, name_a, &mut analysis_a);
        Self::analyze_block_for_dual_accumulator(body, name_b, &mut analysis_b);

        !analysis_a.disqualified
            && analysis_a.self_appends >= 1
            && analysis_a.reads == 0
            && !analysis_b.disqualified
            && analysis_b.self_appends >= 1
            && analysis_b.reads == 0
    }

    /// Like `analyze_block_for_accumulator` but with the relaxed rule that
    /// `acc = acc + ...` may appear more than once (one per branch).
    /// "Reads" of the accumulator as the LEFT-SPINE of a self-append are
    /// NOT counted as external reads (the existing analysis already handles
    /// this correctly — reads are only counted from non-self-append positions).
    fn analyze_block_for_dual_accumulator(
        block: &HirBlock,
        acc_name: &str,
        out: &mut AccumulatorAnalysis,
    ) {
        for stmt in &block.statements {
            Self::analyze_stmt_for_dual_accumulator(stmt, acc_name, out);
            if out.disqualified {
                return;
            }
        }
    }

    /// Like `analyze_stmt_for_accumulator` but counts ALL self-appends
    /// (even multiple per body) and uses the same disqualifier rules.
    fn analyze_stmt_for_dual_accumulator(
        stmt: &HirStatement,
        acc_name: &str,
        out: &mut AccumulatorAnalysis,
    ) {
        match stmt {
            HirStatement::Assignment { target, value, .. } => {
                let HirLValue::Variable { name: lhs_name, .. } = target else {
                    Self::analyze_lvalue_for_accumulator(target, acc_name, out);
                    Self::analyze_expr_for_accumulator(value, acc_name, out);
                    return;
                };
                let is_self_append = Self::is_chained_self_append(value, acc_name);
                if is_self_append {
                    let mut rhs_out = AccumulatorAnalysis::default();
                    Self::analyze_chain_right_operands_for_accumulator(
                        value,
                        acc_name,
                        &mut rhs_out,
                    );
                    if rhs_out.reads > 0 || rhs_out.disqualified {
                        out.disqualified = true;
                        return;
                    }
                    // Count it (may exceed 1 — that's fine for the dual path).
                    out.self_appends += 1;
                } else if lhs_name == acc_name {
                    // Non-canonical write (e.g. `acc = "literal"` in a branch).
                    out.disqualified = true;
                } else {
                    Self::analyze_expr_for_accumulator(value, acc_name, out);
                }
            }
            HirStatement::VariableDeclaration { initializer, .. } => {
                if let Some(init) = initializer {
                    Self::analyze_expr_for_accumulator(init, acc_name, out);
                }
            }
            HirStatement::Expression { expression, .. } => {
                Self::analyze_expr_for_accumulator(expression, acc_name, out);
            }
            HirStatement::Print { expression, .. } => {
                Self::analyze_expr_for_accumulator(expression, acc_name, out);
            }
            HirStatement::Return { .. } => {
                out.disqualified = true;
            }
            HirStatement::If {
                condition,
                then_branch,
                else_branch,
                ..
            } => {
                Self::analyze_expr_for_accumulator(condition, acc_name, out);
                if !out.disqualified {
                    Self::analyze_block_for_dual_accumulator(then_branch, acc_name, out);
                }
                if !out.disqualified {
                    if let Some(else_b) = else_branch {
                        Self::analyze_block_for_dual_accumulator(else_b, acc_name, out);
                    }
                }
            }
            HirStatement::While {
                condition, body, ..
            } => {
                Self::analyze_expr_for_accumulator(condition, acc_name, out);
                if !out.disqualified {
                    Self::analyze_block_for_dual_accumulator(body, acc_name, out);
                }
            }
            HirStatement::For { iterable, body, .. } => {
                Self::analyze_expr_for_accumulator(iterable, acc_name, out);
                if !out.disqualified {
                    Self::analyze_block_for_dual_accumulator(body, acc_name, out);
                }
            }
            HirStatement::Break { .. } | HirStatement::Continue { .. } => {}
            HirStatement::LaterAssignment { expression, .. }
            | HirStatement::Background { expression, .. } => {
                out.disqualified = true;
                Self::analyze_expr_for_accumulator(expression, acc_name, out);
            }
            HirStatement::Require { condition, .. } | HirStatement::Ensure { condition, .. } => {
                Self::analyze_expr_for_accumulator(condition, acc_name, out);
            }
        }
    }

    /// Rewrite a single while/for loop's body to bracket each iteration
    /// with `_arena_scope_push` / `_arena_scope_pop`, reclaiming per-iteration
    /// intermediate LP-strings from the host bump arena in O(1).
    ///
    /// Two rewrite shapes are supported:
    ///
    /// **Flat-body shape** (all self-appends at the loop body's top level):
    ///
    /// ```text
    /// while cond
    ///     ...
    ///     A = A + chain_a_0            →  integer __da_N_atmark = _arena_scope_push()
    ///     A = A + chain_a_1               ...
    ///     B = B + chain_b_0               string __da_N_chunkA_0 = chain_a_0
    ///                                      string __da_N_chunkA_1 = chain_a_1
    ///                                      string __da_N_chunkB_0 = chain_b_0
    ///                                      _arena_scope_pop(__da_N_atmark)
    ///                                      A = A + __da_N_chunkA_0 + __da_N_chunkA_1
    ///                                      B = B + __da_N_chunkB_0
    /// ```
    ///
    /// **Branch-nested shape** (self-appends inside if/else arms):
    ///
    /// ```text
    /// while cond
    ///     if condition
    ///         A = A + chain_a_0        →  if condition
    ///         B = B + chain_b_0               integer __da_M_atmark = _arena_scope_push()
    ///     else                                 string __da_M_chunkA_0 = chain_a_0
    ///         A = A + chain_a_1               string __da_M_chunkB_0 = chain_b_0
    ///         B = B + chain_b_1               _arena_scope_pop(__da_M_atmark)
    ///                                          A = A + __da_M_chunkA_0
    ///                                          B = B + __da_M_chunkB_0
    ///                                      else
    ///                                          integer __da_K_atmark = _arena_scope_push()
    ///                                          string __da_K_chunkA_0 = chain_a_1
    ///                                          string __da_K_chunkB_0 = chain_b_1
    ///                                          _arena_scope_pop(__da_K_atmark)
    ///                                          A = A + __da_K_chunkA_0
    ///                                          B = B + __da_K_chunkB_0
    /// ```
    ///
    /// Each branch arm gets its OWN scope (different counter N). Sibling arms
    /// never share a scope — the push/pop pair is always inside the arm that
    /// actually runs in a given iteration.  Statements that do not touch A or
    /// B are left in their original position, inside or outside the scope as
    /// appropriate (inside the branch, outside the chunk/pop/accumulate tail).
    ///
    /// The recursive worker `apply_dual_scope_rewrite` handles both levels:
    /// top-level appends → chunk extraction (returned to caller for outer scope
    /// wrap), branch-nested appends → inline scope wrap inside the branch body.
    fn try_rewrite_dual_accumulator_loop(
        &mut self,
        loop_stmt: &HirStatement,
        name_a: &str,
        name_b: &str,
        loc: &SourceLocation,
    ) -> Option<HirStatement> {
        let orig_body = match loop_stmt {
            HirStatement::While { body, .. } | HirStatement::For { body, .. } => body.clone(),
            _ => return None,
        };

        // Use the recursive worker.  Top-level chunks from the loop body itself
        // are returned to us; branch-nested chunks are handled inline by the worker.
        let (rewritten_stmts, top_chunks_a, top_chunks_b) = Self::apply_dual_scope_rewrite(
            orig_body.statements,
            name_a,
            name_b,
            &mut self.string_builder_counter,
            loc,
        )?;

        // If neither accumulator has top-level chunks, the branch-level rewrites
        // inside the body were sufficient — no outer scope wrap needed.
        let new_body_stmts = if top_chunks_a.is_empty() && top_chunks_b.is_empty() {
            rewritten_stmts
        } else {
            // Wrap the loop body with a single outer push/pop for the top-level chunks.
            let n = self.string_builder_counter;
            self.string_builder_counter += 1;
            let atmark_name = format!("__da_{}_atmark", n);

            let atmark_decl = HirStatement::VariableDeclaration {
                name: atmark_name.clone(),
                var_type: HirType::Integer,
                initializer: Some(HirExpression::Call {
                    function: "_arena_scope_push".to_string(),
                    arguments: vec![],
                    location: loc.clone(),
                }),
                is_mutable: false,
                location: loc.clone(),
            };

            let pop_stmt = HirStatement::Expression {
                expression: HirExpression::Call {
                    function: "_arena_scope_pop".to_string(),
                    arguments: vec![HirExpression::Variable {
                        name: atmark_name.clone(),
                        location: loc.clone(),
                    }],
                    location: loc.clone(),
                },
                location: loc.clone(),
            };

            let mut body_stmts = rewritten_stmts;
            body_stmts.insert(0, atmark_decl);
            body_stmts.push(pop_stmt);

            // Post-pop accumulation for both A and B (using outer arena).
            if let Some(acc_a) = Self::build_accumulate_stmt(name_a, &top_chunks_a, loc) {
                body_stmts.push(acc_a);
            }
            if let Some(acc_b) = Self::build_accumulate_stmt(name_b, &top_chunks_b, loc) {
                body_stmts.push(acc_b);
            }

            body_stmts
        };

        // Wrap the loop body with a transient arena scope so that body-local
        // string operations (handler_name, path, chunk declarations) route
        // through the WASM transient pool rather than the host arena.
        //
        // This is critical for correctness: the chunk variables (e.g.
        // `__da_N_chunkA_0`) are declared inside branch arms within the loop
        // body and are therefore body-local.  Without the transient scope,
        // their string.concat results land in the HOST arena and are freed
        // by `_arena_scope_pop`, making their pointers dangle before the
        // post-pop accumulation step can read them.
        //
        // With the transient scope, body-local concat results go to the WASM
        // transient pool (call 174), which is independent of the host arena
        // and is NOT reset by `_arena_scope_pop`.  The post-pop accumulation
        // `result = result + chunk` then uses HOST string.concat (call 14) to
        // produce a new host-arena LP-string for the long-lived accumulator.
        // The transient pool is flushed by `transient_scope_exit` at the end
        // of each loop iteration.
        let mut new_body = HirBlock {
            statements: new_body_stmts,
            location: orig_body.location.clone(),
        };
        let mut body_local_string_names = std::collections::HashSet::new();
        Self::collect_body_local_string_names(&new_body, &mut body_local_string_names);
        Self::rewrite_body_local_helpers_to_transient(&mut new_body, &body_local_string_names);

        // Add transient_scope_enter at the start and transient_scope_exit at the end.
        let tmark_name = format!("__da_{}_tmark", self.string_builder_counter);
        self.string_builder_counter += 1;
        let tmark_decl = HirStatement::VariableDeclaration {
            name: tmark_name.clone(),
            var_type: HirType::Integer,
            initializer: Some(HirExpression::Call {
                function: "transient_scope_enter".to_string(),
                arguments: vec![],
                location: loc.clone(),
            }),
            is_mutable: false,
            location: loc.clone(),
        };
        let tmark_exit = HirStatement::Expression {
            expression: HirExpression::Call {
                function: "transient_scope_exit".to_string(),
                arguments: vec![HirExpression::Variable {
                    name: tmark_name.clone(),
                    location: loc.clone(),
                }],
                location: loc.clone(),
            },
            location: loc.clone(),
        };
        new_body.statements.insert(0, tmark_decl);
        new_body.statements.push(tmark_exit);

        Some(match loop_stmt {
            HirStatement::While {
                condition,
                location,
                ..
            } => HirStatement::While {
                condition: condition.clone(),
                body: new_body,
                location: location.clone(),
            },
            HirStatement::For {
                variable,
                iterable,
                location,
                ..
            } => HirStatement::For {
                variable: variable.clone(),
                iterable: iterable.clone(),
                body: new_body,
                location: location.clone(),
            },
            _ => return None,
        })
    }

    /// Recursive worker for the dual-accumulator scope rewrite.
    ///
    /// Processes a flat list of HIR statements, replacing top-level self-appends
    /// and recursing into if/else branches.
    ///
    /// Returns `(rewritten_stmts, top_chunk_names_a, top_chunk_names_b)` where:
    /// - `rewritten_stmts`: the transformed statement list.
    /// - `top_chunk_names_a/b`: chunk variable names for appends that were
    ///   at the TOP LEVEL of this list (the caller is responsible for wrapping
    ///   with push/pop/accumulate).
    ///
    /// For if/else branches that contain appends, the branch body is rewritten
    /// in-place: the self-appends become chunk declarations, a push/pop scope
    /// wraps them, and the accumulation assignments follow the pop — all INSIDE
    /// the branch body.  The outer caller sees no chunks for these appends (they
    /// are fully resolved inside the branch).
    ///
    /// Returns `None` if any chain-strip operation fails (malformed HIR), which
    /// causes the entire rewrite to be aborted.
    fn apply_dual_scope_rewrite(
        stmts: Vec<HirStatement>,
        name_a: &str,
        name_b: &str,
        counter: &mut usize,
        loc: &SourceLocation,
    ) -> Option<(Vec<HirStatement>, Vec<String>, Vec<String>)> {
        let mut out: Vec<HirStatement> = Vec::with_capacity(stmts.len());
        let mut top_chunk_names_a: Vec<String> = Vec::new();
        let mut top_chunk_names_b: Vec<String> = Vec::new();

        for stmt in stmts {
            match stmt {
                // ── Top-level self-append on A or B ──────────────────────────
                HirStatement::Assignment {
                    ref target,
                    ref value,
                    ref location,
                } if matches!(
                    target,
                    HirLValue::Variable { name, .. } if (name == name_a || name == name_b)
                ) && {
                    let lhs_name = match target {
                        HirLValue::Variable { name, .. } => name.as_str(),
                        _ => "",
                    };
                    Self::is_chained_self_append(value, lhs_name)
                } =>
                {
                    let lhs_name = match target {
                        HirLValue::Variable { name, .. } => name.as_str(),
                        _ => unreachable!(),
                    };
                    let n = *counter;
                    *counter += 1;

                    let (chunk_name, chunk_list) = if lhs_name == name_a {
                        let idx = top_chunk_names_a.len();
                        let name = format!("__da_{}_chunkA_{}", n, idx);
                        top_chunk_names_a.push(name.clone());
                        (name, &mut top_chunk_names_a)
                    } else {
                        let idx = top_chunk_names_b.len();
                        let name = format!("__da_{}_chunkB_{}", n, idx);
                        top_chunk_names_b.push(name.clone());
                        (name, &mut top_chunk_names_b)
                    };
                    // `chunk_list` borrow ends here (used only for push above).
                    let _ = chunk_list;

                    let chain_without_acc = Self::strip_leftmost_variable_from_chain(value)?;

                    out.push(HirStatement::VariableDeclaration {
                        name: chunk_name,
                        var_type: HirType::String,
                        initializer: Some(chain_without_acc),
                        is_mutable: false,
                        location: location.clone(),
                    });
                }

                // ── If/else statement: recurse into each branch ───────────────
                HirStatement::If {
                    condition,
                    then_branch,
                    else_branch,
                    location: if_loc,
                } => {
                    // Check whether this if/else touches A or B at all.
                    let branch_has_append = |blk: &HirBlock| {
                        let mut a = AccumulatorAnalysis::default();
                        let mut b = AccumulatorAnalysis::default();
                        Self::analyze_block_for_dual_accumulator(blk, name_a, &mut a);
                        Self::analyze_block_for_dual_accumulator(blk, name_b, &mut b);
                        a.self_appends > 0 || b.self_appends > 0
                    };

                    let then_has = branch_has_append(&then_branch);
                    let else_has = else_branch.as_ref().map(branch_has_append).unwrap_or(false);

                    if !then_has && !else_has {
                        // No appends anywhere in this if/else — pass through unchanged.
                        out.push(HirStatement::If {
                            condition,
                            then_branch,
                            else_branch,
                            location: if_loc,
                        });
                        continue;
                    }

                    // Rewrite the then-branch.
                    let new_then_branch = if then_has {
                        Self::rewrite_branch_with_scope(then_branch, name_a, name_b, counter, loc)?
                    } else {
                        then_branch
                    };

                    // Rewrite the else-branch (if present and if it has appends).
                    let new_else_branch = match else_branch {
                        Some(blk) if else_has => Some(Self::rewrite_branch_with_scope(
                            blk, name_a, name_b, counter, loc,
                        )?),
                        other => other,
                    };

                    out.push(HirStatement::If {
                        condition,
                        then_branch: new_then_branch,
                        else_branch: new_else_branch,
                        location: if_loc,
                    });
                }

                // ── All other statements pass through unchanged ────────────────
                other => {
                    out.push(other);
                }
            }
        }

        Some((out, top_chunk_names_a, top_chunk_names_b))
    }

    /// Rewrite a single branch body (an if/else arm) so that all self-appends
    /// to `name_a` and `name_b` within it are wrapped in their own arena scope.
    ///
    /// The transformed branch body has the shape:
    /// ```text
    ///   <non-append stmts before first append, unchanged>
    ///   integer __da_N_atmark = _arena_scope_push()
    ///   string __da_N_chunkA_0 = chain_a_0     -- extracted from A = A + chain_a_0
    ///   string __da_N_chunkB_0 = chain_b_0     -- extracted from B = B + chain_b_0
    ///   <non-append stmts that were between appends, unchanged>
    ///   _arena_scope_pop(__da_N_atmark)
    ///   A = A + __da_N_chunkA_0                -- post-pop accumulation
    ///   B = B + __da_N_chunkB_0
    /// ```
    ///
    /// This is done by recursively calling `apply_dual_scope_rewrite` on the
    /// branch's statements to extract the chunks, then wrapping with push/pop and
    /// the post-pop accumulation.  Sub-branches (nested if/else inside this arm)
    /// are handled by `apply_dual_scope_rewrite` recursively.
    fn rewrite_branch_with_scope(
        branch: HirBlock,
        name_a: &str,
        name_b: &str,
        counter: &mut usize,
        loc: &SourceLocation,
    ) -> Option<HirBlock> {
        let branch_loc = branch.location.clone();

        // Recursively apply the rewrite to the branch's statements.
        // The returned top_chunks are the appends that were at the branch's top level;
        // any deeper nesting is already handled inline by apply_dual_scope_rewrite.
        let (branch_stmts, branch_chunks_a, branch_chunks_b) =
            Self::apply_dual_scope_rewrite(branch.statements, name_a, name_b, counter, loc)?;

        // If neither A nor B had any top-level appends in this branch body,
        // the sub-branch rewrites (if any) already handled everything inline.
        // No scope wrap needed at this level.
        if branch_chunks_a.is_empty() && branch_chunks_b.is_empty() {
            return Some(HirBlock {
                statements: branch_stmts,
                location: branch_loc,
            });
        }

        // Wrap the branch body with its own push/pop scope.
        let n = *counter;
        *counter += 1;
        let atmark_name = format!("__da_{}_atmark", n);

        let atmark_decl = HirStatement::VariableDeclaration {
            name: atmark_name.clone(),
            var_type: HirType::Integer,
            initializer: Some(HirExpression::Call {
                function: "_arena_scope_push".to_string(),
                arguments: vec![],
                location: loc.clone(),
            }),
            is_mutable: false,
            location: loc.clone(),
        };

        let pop_stmt = HirStatement::Expression {
            expression: HirExpression::Call {
                function: "_arena_scope_pop".to_string(),
                arguments: vec![HirExpression::Variable {
                    name: atmark_name.clone(),
                    location: loc.clone(),
                }],
                location: loc.clone(),
            },
            location: loc.clone(),
        };

        let mut new_branch_stmts = branch_stmts;
        new_branch_stmts.insert(0, atmark_decl);
        new_branch_stmts.push(pop_stmt);

        if let Some(acc_a) = Self::build_accumulate_stmt(name_a, &branch_chunks_a, loc) {
            new_branch_stmts.push(acc_a);
        }
        if let Some(acc_b) = Self::build_accumulate_stmt(name_b, &branch_chunks_b, loc) {
            new_branch_stmts.push(acc_b);
        }

        Some(HirBlock {
            statements: new_branch_stmts,
            location: branch_loc,
        })
    }

    /// Build `acc_name = acc_name + chunk_0 + chunk_1 + ...` as a left-folded
    /// `HirStatement::Assignment`.  Returns `None` if `chunk_names` is empty.
    fn build_accumulate_stmt(
        acc_name: &str,
        chunk_names: &[String],
        loc: &SourceLocation,
    ) -> Option<HirStatement> {
        if chunk_names.is_empty() {
            return None;
        }
        let mut expr = HirExpression::Variable {
            name: acc_name.to_string(),
            location: loc.clone(),
        };
        for chunk_name in chunk_names {
            expr = HirExpression::BinaryOp {
                left: Box::new(expr),
                op: HirBinaryOp::Add,
                right: Box::new(HirExpression::Variable {
                    name: chunk_name.clone(),
                    location: loc.clone(),
                }),
                location: loc.clone(),
            };
        }
        Some(HirStatement::Assignment {
            target: HirLValue::Variable {
                name: acc_name.to_string(),
                location: loc.clone(),
            },
            value: expr,
            location: loc.clone(),
        })
    }

    /// Strip the leftmost variable atom from a left-folded `+` chain.
    ///
    /// For `acc + e1 + e2 + e3` (parsed as `((acc + e1) + e2) + e3`),
    /// returns `e1 + e2 + e3` (i.e., drops the `acc` and rebuilds the chain
    /// from its right-spine fragments in left-fold order).
    ///
    /// Returns `None` if the expression is not a chained self-append.
    fn strip_leftmost_variable_from_chain(expr: &HirExpression) -> Option<HirExpression> {
        // Collect right-spine fragments in reverse order (rightmost first).
        let mut fragments: Vec<HirExpression> = Vec::new();
        let mut cur = expr;
        loop {
            match cur {
                HirExpression::BinaryOp {
                    left,
                    op: HirBinaryOp::Add | HirBinaryOp::StringConcat,
                    right,
                    ..
                } => {
                    fragments.push(*right.clone());
                    cur = left.as_ref();
                }
                HirExpression::Variable { .. } => {
                    // Reached the leftmost variable — stop.
                    break;
                }
                _ => return None,
            }
        }

        if fragments.is_empty() {
            // `acc + nothing` — shouldn't happen since is_chained_self_append
            // requires at least one right operand.
            return None;
        }

        // Fragments are in reverse order; reverse to get source order.
        fragments.reverse();

        // Rebuild as a left-folded chain.
        let mut result = fragments.remove(0);
        for frag in fragments {
            result = HirExpression::BinaryOp {
                left: Box::new(result),
                op: HirBinaryOp::Add,
                right: Box::new(frag),
                location: SourceLocation::default(),
            };
        }
        Some(result)
    }

    /// Walk every statement and every expression in the block, accumulating
    /// info about how `acc_name` is touched.
    fn analyze_block_for_accumulator(
        block: &HirBlock,
        acc_name: &str,
        out: &mut AccumulatorAnalysis,
    ) {
        for stmt in &block.statements {
            Self::analyze_stmt_for_accumulator(stmt, acc_name, out);
            if out.disqualified {
                return;
            }
        }
    }

    fn analyze_stmt_for_accumulator(
        stmt: &HirStatement,
        acc_name: &str,
        out: &mut AccumulatorAnalysis,
    ) {
        match stmt {
            HirStatement::Assignment { target, value, .. } => {
                // Is this the canonical self-append?
                let HirLValue::Variable { name: lhs_name, .. } = target else {
                    // Field/index assignment — recurse into LHS object/index expressions.
                    Self::analyze_lvalue_for_accumulator(target, acc_name, out);
                    Self::analyze_expr_for_accumulator(value, acc_name, out);
                    return;
                };
                // Single-RHS form: `acc = acc + e`.
                // Chained-RHS form: `acc = acc + e1 + e2 + … + eN` which parses
                // as `((acc + e1) + e2) + … + eN`. The leftmost atom of the
                // left-spine must be `Variable(acc)`; no intermediate node may
                // read `acc` in its right operand.
                let is_chained_self_append = Self::is_chained_self_append(value, acc_name);
                if is_chained_self_append {
                    // Every right operand of the left-spine must not read `acc`.
                    let mut rhs_out = AccumulatorAnalysis::default();
                    Self::analyze_chain_right_operands_for_accumulator(
                        value,
                        acc_name,
                        &mut rhs_out,
                    );
                    if rhs_out.reads > 0 || rhs_out.disqualified {
                        // e.g. `acc = acc + acc + x` — a chain RHS reads acc.
                        out.disqualified = true;
                        return;
                    }
                    out.self_appends += 1;
                } else if lhs_name == acc_name {
                    // Some other write to acc (e.g. `acc = "literal"` or
                    // `acc = other + acc` prepend). Disqualified.
                    out.disqualified = true;
                } else {
                    // Unrelated assignment — but its RHS might still read acc.
                    Self::analyze_expr_for_accumulator(value, acc_name, out);
                }
            }
            HirStatement::VariableDeclaration { initializer, .. } => {
                if let Some(init) = initializer {
                    Self::analyze_expr_for_accumulator(init, acc_name, out);
                }
            }
            HirStatement::Expression { expression, .. } => {
                Self::analyze_expr_for_accumulator(expression, acc_name, out);
            }
            HirStatement::Print { expression, .. } => {
                Self::analyze_expr_for_accumulator(expression, acc_name, out);
            }
            HirStatement::Return { value, .. } => {
                // An early return inside the loop body is an escape — even if
                // it doesn't reference `acc` directly, the user might
                // depend on `acc` having been observable. Bail.
                out.disqualified = true;
                if let Some(v) = value {
                    Self::analyze_expr_for_accumulator(v, acc_name, out);
                }
            }
            HirStatement::If {
                condition,
                then_branch,
                else_branch,
                ..
            } => {
                Self::analyze_expr_for_accumulator(condition, acc_name, out);
                Self::analyze_block_for_accumulator(then_branch, acc_name, out);
                if let Some(else_b) = else_branch {
                    Self::analyze_block_for_accumulator(else_b, acc_name, out);
                }
            }
            HirStatement::While {
                condition, body, ..
            } => {
                Self::analyze_expr_for_accumulator(condition, acc_name, out);
                Self::analyze_block_for_accumulator(body, acc_name, out);
            }
            HirStatement::For { iterable, body, .. } => {
                Self::analyze_expr_for_accumulator(iterable, acc_name, out);
                Self::analyze_block_for_accumulator(body, acc_name, out);
            }
            HirStatement::Break { .. } => {
                // A break leaves the builder in a state where the rebound
                // `acc = finalize(...)` after the loop would still execute,
                // but mixing partial state with the original semantics is
                // risky enough to bail on. Most break-using loops are not
                // simple accumulators anyway.
                out.disqualified = true;
            }
            HirStatement::Continue { .. } => {
                // Continue is fine — it just skips the remainder of this
                // iteration. No bail needed.
            }
            HirStatement::LaterAssignment { expression, .. }
            | HirStatement::Background { expression, .. } => {
                // Suspension points could observe `acc` from elsewhere.
                out.disqualified = true;
                Self::analyze_expr_for_accumulator(expression, acc_name, out);
            }
            HirStatement::Require { condition, .. } | HirStatement::Ensure { condition, .. } => {
                Self::analyze_expr_for_accumulator(condition, acc_name, out);
            }
        }
    }

    /// True when `expr` is a left-folded chain of `+`/`StringConcat` whose
    /// leftmost atom is `Variable(acc_name)`. Examples that return true:
    ///   `acc + e`                       (depth 1, single-RHS)
    ///   `(acc + e1) + e2`               (depth 2)
    ///   `((acc + e1) + e2) + e3`        (depth 3, three-fragment chain)
    /// Returns false if the leftmost atom is anything else, or if any node
    /// uses a non-concatenating operator.
    fn is_chained_self_append(expr: &HirExpression, acc_name: &str) -> bool {
        let mut cur = expr;
        loop {
            match cur {
                HirExpression::BinaryOp {
                    left,
                    op: HirBinaryOp::Add | HirBinaryOp::StringConcat,
                    ..
                } => {
                    cur = left.as_ref();
                }
                HirExpression::Variable { name, .. } => return name == acc_name,
                _ => return false,
            }
        }
    }

    /// Walk the right operands of a left-folded `+` chain rooted at `expr`
    /// (whose leftmost atom is `acc_name`) and accumulate reads/disqualifiers.
    /// Called by `analyze_stmt_for_accumulator` to verify the chain's RHS
    /// fragments don't read `acc` (which would break the rewrite invariant).
    fn analyze_chain_right_operands_for_accumulator(
        expr: &HirExpression,
        acc_name: &str,
        out: &mut AccumulatorAnalysis,
    ) {
        let mut cur = expr;
        loop {
            match cur {
                HirExpression::BinaryOp {
                    left,
                    op: HirBinaryOp::Add | HirBinaryOp::StringConcat,
                    right,
                    ..
                } => {
                    Self::analyze_expr_for_accumulator(right, acc_name, out);
                    if out.disqualified {
                        return;
                    }
                    cur = left.as_ref();
                }
                _ => return,
            }
        }
    }

    fn analyze_lvalue_for_accumulator(
        lvalue: &HirLValue,
        acc_name: &str,
        out: &mut AccumulatorAnalysis,
    ) {
        match lvalue {
            HirLValue::Variable { .. } => {
                // Handled by the caller (this is for non-Variable lvalues only).
            }
            HirLValue::FieldAccess { object, .. } => {
                Self::analyze_expr_for_accumulator(object, acc_name, out);
            }
            HirLValue::Index { array, index, .. } => {
                Self::analyze_expr_for_accumulator(array, acc_name, out);
                Self::analyze_expr_for_accumulator(index, acc_name, out);
            }
        }
    }

    fn analyze_expr_for_accumulator(
        expr: &HirExpression,
        acc_name: &str,
        out: &mut AccumulatorAnalysis,
    ) {
        match expr {
            HirExpression::Variable { name, .. } => {
                if name == acc_name {
                    out.reads += 1;
                }
            }
            HirExpression::Literal { .. } => {}
            HirExpression::BinaryOp { left, right, .. } => {
                Self::analyze_expr_for_accumulator(left, acc_name, out);
                Self::analyze_expr_for_accumulator(right, acc_name, out);
            }
            HirExpression::UnaryOp { operand, .. } => {
                Self::analyze_expr_for_accumulator(operand, acc_name, out);
            }
            HirExpression::Call { arguments, .. } => {
                for arg in arguments {
                    Self::analyze_expr_for_accumulator(arg, acc_name, out);
                }
            }
            HirExpression::MethodCall {
                receiver,
                arguments,
                ..
            } => {
                Self::analyze_expr_for_accumulator(receiver, acc_name, out);
                for arg in arguments {
                    Self::analyze_expr_for_accumulator(arg, acc_name, out);
                }
            }
            HirExpression::FieldAccess { object, .. } => {
                Self::analyze_expr_for_accumulator(object, acc_name, out);
            }
            HirExpression::Index { array, index, .. } => {
                Self::analyze_expr_for_accumulator(array, acc_name, out);
                Self::analyze_expr_for_accumulator(index, acc_name, out);
            }
            HirExpression::Array { elements, .. } => {
                for e in elements {
                    Self::analyze_expr_for_accumulator(e, acc_name, out);
                }
            }
            HirExpression::Constructor { arguments, .. } => {
                for arg in arguments {
                    Self::analyze_expr_for_accumulator(arg, acc_name, out);
                }
            }
            HirExpression::Cast { expression, .. } => {
                Self::analyze_expr_for_accumulator(expression, acc_name, out);
            }
            HirExpression::Assignment { target, value, .. } => {
                // An assignment-expression to `acc` is an escape we don't model.
                if let HirLValue::Variable { name, .. } = target {
                    if name == acc_name {
                        out.disqualified = true;
                    }
                }
                Self::analyze_lvalue_for_accumulator(target, acc_name, out);
                Self::analyze_expr_for_accumulator(value, acc_name, out);
            }
            HirExpression::NamespaceCall { arguments, .. } => {
                for arg in arguments {
                    Self::analyze_expr_for_accumulator(arg, acc_name, out);
                }
            }
            HirExpression::StaticMethodCall { arguments, .. } => {
                for arg in arguments {
                    Self::analyze_expr_for_accumulator(arg, acc_name, out);
                }
            }
            HirExpression::OnError {
                expression,
                fallback,
                ..
            } => {
                Self::analyze_expr_for_accumulator(expression, acc_name, out);
                Self::analyze_expr_for_accumulator(fallback, acc_name, out);
            }
            HirExpression::Conditional {
                condition,
                then_expr,
                else_expr,
                ..
            } => {
                Self::analyze_expr_for_accumulator(condition, acc_name, out);
                Self::analyze_expr_for_accumulator(then_expr, acc_name, out);
                Self::analyze_expr_for_accumulator(else_expr, acc_name, out);
            }
            HirExpression::BaseCall { arguments, .. } => {
                for arg in arguments {
                    Self::analyze_expr_for_accumulator(arg, acc_name, out);
                }
            }
            HirExpression::Range {
                start, end, step, ..
            } => {
                Self::analyze_expr_for_accumulator(start, acc_name, out);
                Self::analyze_expr_for_accumulator(end, acc_name, out);
                if let Some(s) = step {
                    Self::analyze_expr_for_accumulator(s, acc_name, out);
                }
            }
            HirExpression::ObjectLiteral { fields, .. } => {
                for (_, value) in fields {
                    Self::analyze_expr_for_accumulator(value, acc_name, out);
                }
            }
        }
    }

    /// After analysis confirms the body is rewritable, walk it again to
    /// replace the single canonical self-append statement.
    fn rewrite_self_append_in_block(block: &mut HirBlock, acc_name: &str, sb_name: &str) {
        // Two-pass walk because chained-RHS rewrites turn a single
        // assignment into N sequential statements. Pass 1 transforms each
        // statement *in place* into a possibly-Vec-valued replacement;
        // Pass 2 flattens the Vec back into the block.
        let mut new_stmts: Vec<HirStatement> = Vec::with_capacity(block.statements.len());
        for stmt in std::mem::take(&mut block.statements).into_iter() {
            Self::rewrite_self_append_collect(stmt, acc_name, sb_name, &mut new_stmts);
        }
        block.statements = new_stmts;
    }

    /// Lower one input statement into 1+ output statements, appending them
    /// to `out`. The chained-RHS case is the only one that produces more
    /// than one output: `acc = acc + e1 + e2 + e3` becomes three
    /// `sb = string_builder_append(sb, eK)` statements in source order.
    fn rewrite_self_append_collect(
        stmt: HirStatement,
        acc_name: &str,
        sb_name: &str,
        out: &mut Vec<HirStatement>,
    ) {
        match stmt {
            HirStatement::Assignment {
                target: HirLValue::Variable { name: lhs_name, .. },
                value,
                location,
            } if lhs_name == acc_name && Self::is_chained_self_append(&value, acc_name) => {
                // Flatten the left-folded chain into source-order RHS
                // fragments. For `((acc + e1) + e2) + e3`, the walk yields
                // `[e3, e2, e1]` (because we descend `left` while
                // collecting `right`), so we reverse before emitting.
                let mut fragments: Vec<HirExpression> = Vec::new();
                let mut cur = value;
                while let HirExpression::BinaryOp {
                    left,
                    op: HirBinaryOp::Add | HirBinaryOp::StringConcat,
                    right,
                    ..
                } = cur
                {
                    fragments.push(*right);
                    cur = *left;
                }
                fragments.reverse();

                for frag in fragments {
                    out.push(HirStatement::Assignment {
                        target: HirLValue::Variable {
                            name: sb_name.to_string(),
                            location: location.clone(),
                        },
                        value: HirExpression::Call {
                            function: "string_builder_append".to_string(),
                            arguments: vec![
                                HirExpression::Variable {
                                    name: sb_name.to_string(),
                                    location: location.clone(),
                                },
                                frag,
                            ],
                            location: location.clone(),
                        },
                        location: location.clone(),
                    });
                }
            }
            HirStatement::Assignment { .. } => {
                // Other assignments — including non-Variable lvalues — are not
                // the canonical self-append. The accumulator analysis pass has
                // already verified `acc_name` is not touched here.
                out.push(stmt);
            }
            HirStatement::If {
                condition,
                mut then_branch,
                mut else_branch,
                location,
            } => {
                Self::rewrite_self_append_in_block(&mut then_branch, acc_name, sb_name);
                if let Some(eb) = else_branch.as_mut() {
                    Self::rewrite_self_append_in_block(eb, acc_name, sb_name);
                }
                out.push(HirStatement::If {
                    condition,
                    then_branch,
                    else_branch,
                    location,
                });
            }
            HirStatement::While {
                condition,
                mut body,
                location,
            } => {
                Self::rewrite_self_append_in_block(&mut body, acc_name, sb_name);
                out.push(HirStatement::While {
                    condition,
                    body,
                    location,
                });
            }
            HirStatement::For {
                variable,
                iterable,
                mut body,
                location,
            } => {
                Self::rewrite_self_append_in_block(&mut body, acc_name, sb_name);
                out.push(HirStatement::For {
                    variable,
                    iterable,
                    body,
                    location,
                });
            }
            other => out.push(other),
        }
    }

    /// Collect every body-local string-typed local declared anywhere
    /// inside `block` (descending into nested blocks). Used to determine
    /// which named locals are safe transient-arena targets in
    /// `rewrite_body_local_helpers_to_transient`.
    ///
    /// "Body-local" here means "declared inside the rewritten loop
    /// body's HirBlock or one of its nested blocks." A declaration
    /// captured by this walk will be torn down (the local goes out of
    /// scope and any pointer it holds is unreachable) at the end of
    /// each iteration, which is exactly when the matching
    /// `__transient_scope_exit` resets the transient pool. So routing
    /// the local's allocation through `__transient_alloc` is
    /// lifetime-safe by construction.
    ///
    /// Names declared in the OUTER scope (above the rewritten loop) are
    /// NOT captured — those continue to allocate via `__malloc` and
    /// live on the main heap. That is the invariant that prevents
    /// CMP-SSR-RECLAIM-FREES-LIVE-POINTER from reappearing: a
    /// `head = json.get(...)` reassignment at the bottom of the body,
    /// where `head` was declared OUTSIDE the loop, never ends up in
    /// `body_local_string_names`, so its concat-shaped initializer (if
    /// any) stays on the main heap.
    fn collect_body_local_string_names(
        block: &HirBlock,
        out: &mut std::collections::HashSet<String>,
    ) {
        for stmt in &block.statements {
            match stmt {
                HirStatement::VariableDeclaration {
                    name,
                    var_type: HirType::String,
                    ..
                } => {
                    out.insert(name.clone());
                }
                HirStatement::If {
                    then_branch,
                    else_branch,
                    ..
                } => {
                    Self::collect_body_local_string_names(then_branch, out);
                    if let Some(eb) = else_branch {
                        Self::collect_body_local_string_names(eb, out);
                    }
                }
                HirStatement::While { body, .. } | HirStatement::For { body, .. } => {
                    Self::collect_body_local_string_names(body, out);
                }
                _ => {}
            }
        }
    }

    /// Walk `block` (descending into nested blocks). For every
    /// `Assignment` whose LHS variable is in `body_local_string_names`
    /// and whose RHS is a `BinaryOp::Add` / `StringConcat` chain,
    /// rewrite the chain into a left-folded sequence of
    /// `Call { function: "string_concat_transient", arguments: [acc, frag] }`
    /// expressions. The result is allocated through `__transient_alloc`
    /// (see `src/codegen/native_stdlib/transient_arena.rs`) and is
    /// reclaimed at the end of the iteration by the
    /// `__transient_scope_exit` call appended in Step 4a' of
    /// `try_match_accumulator_pair`.
    ///
    /// Caller invariant: `block` MUST already be wrapped by a matching
    /// `__transient_scope_enter` / `__transient_scope_exit` pair (that
    /// is, this method is only safe to call from within
    /// `try_match_accumulator_pair`, after `rewrite_self_append_in_block`
    /// has run and before the enter/exit pair is inserted). Calling
    /// from any other context produces transient allocations that
    /// outlive their scope and dangle.
    ///
    /// The chain unfolding mirrors `rewrite_self_append_collect`'s
    /// left-spine walk: `((a + b) + c) + d` becomes
    /// `concat(concat(concat(a, b), c), d)` so that source-order is
    /// preserved.
    ///
    /// Why this is safe even for nested HIR shapes (e.g. an
    /// assignment inside an `if`): the recursive walk visits every
    /// statement in the body, but `body_local_string_names` was
    /// collected from the ENTIRE body before this walk began. A name
    /// declared in one branch and assigned in another is still
    /// body-local — its lifetime ends at the same iteration boundary
    /// regardless of which branch the assignment occurred in. The
    /// transient pool reset at end-of-iter applies uniformly.
    fn rewrite_body_local_helpers_to_transient(
        block: &mut HirBlock,
        body_local_string_names: &std::collections::HashSet<String>,
    ) {
        for stmt in &mut block.statements {
            match stmt {
                HirStatement::Assignment {
                    target: HirLValue::Variable { name, .. },
                    value,
                    ..
                } if body_local_string_names.contains(name) => {
                    if Self::is_string_concat_chain(value) {
                        let owned_value =
                            std::mem::replace(value, Self::placeholder_void_expression());
                        *value = Self::fold_concat_chain_to_transient_calls(owned_value);
                    } else {
                        // Even when the top-level RHS isn't a concat chain
                        // (e.g. `acc = someFunc(x + y)`), nested concats inside
                        // function-call arguments are still transient-safe —
                        // see `rewrite_call_arg_concats_in_expression` for the
                        // safety argument.
                        Self::rewrite_call_arg_concats_in_expression(value);
                    }
                }
                HirStatement::VariableDeclaration {
                    name,
                    var_type: HirType::String,
                    initializer: Some(init),
                    ..
                } if body_local_string_names.contains(name) => {
                    if Self::is_string_concat_chain(init) {
                        let owned_init =
                            std::mem::replace(init, Self::placeholder_void_expression());
                        *init = Self::fold_concat_chain_to_transient_calls(owned_init);
                    } else {
                        Self::rewrite_call_arg_concats_in_expression(init);
                    }
                }
                HirStatement::Assignment { value, .. } => {
                    // Assignment to a non-body-local LHS (e.g. an outer-scope
                    // variable, a field, or a list element). The assignment's
                    // top-level result MUST stay on the main heap, but concat
                    // chains nested inside function-call arguments within the
                    // RHS are still transient-safe — their lifetime ends at
                    // the call's return, well before the iteration boundary.
                    Self::rewrite_call_arg_concats_in_expression(value);
                }
                HirStatement::VariableDeclaration {
                    initializer: Some(init),
                    ..
                } => {
                    Self::rewrite_call_arg_concats_in_expression(init);
                }
                HirStatement::Expression { expression, .. } => {
                    // Expression statements (typically void calls like
                    // `printl(idx + ".preamble")`) — the call consumes its
                    // arguments and produces no value the surrounding scope
                    // can hold. Concat chains in the args are safe to route.
                    Self::rewrite_call_arg_concats_in_expression(expression);
                }
                HirStatement::If {
                    condition,
                    then_branch,
                    else_branch,
                    ..
                } => {
                    Self::rewrite_call_arg_concats_in_expression(condition);
                    Self::rewrite_body_local_helpers_to_transient(
                        then_branch,
                        body_local_string_names,
                    );
                    if let Some(eb) = else_branch {
                        Self::rewrite_body_local_helpers_to_transient(eb, body_local_string_names);
                    }
                }
                HirStatement::While {
                    condition, body, ..
                } => {
                    Self::rewrite_call_arg_concats_in_expression(condition);
                    Self::rewrite_body_local_helpers_to_transient(body, body_local_string_names);
                }
                HirStatement::For { body, .. } => {
                    Self::rewrite_body_local_helpers_to_transient(body, body_local_string_names);
                }
                _ => {}
            }
        }
    }

    /// Walk `expr` recursively and rewrite every `BinaryOp::Add` /
    /// `StringConcat` chain found inside a `Call` or `MethodCall`
    /// argument list to use `string_concat_transient`.
    ///
    /// Safety argument: a value produced as a function-call argument is
    /// consumed by the call. Its lifetime ends at the call's return —
    /// strictly before the surrounding iteration boundary, regardless
    /// of where the call's *result* flows. So routing the arg's
    /// allocation through `__transient_alloc` cannot dangle anything.
    ///
    /// Concrete repro shape (`buildExamples` in
    /// `app/ui/web/pages/tutorials/[id].cln` on Web Site Clean):
    ///   `json.get(examplesJson, idx + ".preamble")`
    /// The `idx + ".preamble"` concat was allocating ~50 bytes per call
    /// × 4 paths (.code, .preamble, .output, .explanation) × ~50 iters
    /// × ~30 tutorials, and the doubling-StringBuilder accumulator did
    /// not catch it because the concat result is a call argument, not
    /// an assignment target. Step 3 (commit `42c63311`) routed the
    /// `headHtml = ...` shape but missed this one.
    ///
    /// The walker descends through:
    ///   - `Call` / `MethodCall` argument lists (the transient sites)
    ///   - `BinaryOp` operands (concats inside operands)
    ///   - `If` / parenthesized / unary wrappers
    ///   - `FieldAccess` receivers
    ///
    /// It does NOT descend into already-rewritten
    /// `Call { function: "string_concat_transient" }` arguments to
    /// avoid double-rewrite churn (no correctness impact; just
    /// pointless work).
    fn rewrite_call_arg_concats_in_expression(expr: &mut HirExpression) {
        match expr {
            HirExpression::Call {
                function,
                arguments,
                ..
            } => {
                let already_transient = function == "string_concat_transient";
                for arg in arguments.iter_mut() {
                    // Recurse into the arg's sub-structure first so any
                    // nested calls inside it get rewritten too.
                    Self::rewrite_call_arg_concats_in_expression(arg);
                    if !already_transient && Self::is_provably_string_concat_chain(arg) {
                        let owned = std::mem::replace(arg, Self::placeholder_void_expression());
                        *arg = Self::fold_concat_chain_to_transient_calls(owned);
                    }
                }
            }
            HirExpression::MethodCall {
                receiver,
                arguments,
                ..
            } => {
                Self::rewrite_call_arg_concats_in_expression(receiver);
                // Also rewrite the receiver itself if it is a concat
                // chain with at least one string literal. Strings are
                // immutable in Clean Language, so a string-typed
                // receiver value cannot be stored beyond the call by a
                // method invocation — its lifetime ends at the
                // method's return, same guarantee as a call-arg.
                // Concrete shape: `("[" + idx + "]").length()` — the
                // concat is the receiver of `length`, dies at length's
                // return, transient-safe.
                if Self::is_provably_string_concat_chain(receiver) {
                    let owned =
                        std::mem::replace(receiver.as_mut(), Self::placeholder_void_expression());
                    *receiver.as_mut() = Self::fold_concat_chain_to_transient_calls(owned);
                }
                for arg in arguments.iter_mut() {
                    Self::rewrite_call_arg_concats_in_expression(arg);
                    if Self::is_provably_string_concat_chain(arg) {
                        let owned = std::mem::replace(arg, Self::placeholder_void_expression());
                        *arg = Self::fold_concat_chain_to_transient_calls(owned);
                    }
                }
            }
            HirExpression::NamespaceCall { arguments, .. }
            | HirExpression::StaticMethodCall { arguments, .. }
            | HirExpression::Constructor { arguments, .. } => {
                for arg in arguments.iter_mut() {
                    Self::rewrite_call_arg_concats_in_expression(arg);
                    if Self::is_provably_string_concat_chain(arg) {
                        let owned = std::mem::replace(arg, Self::placeholder_void_expression());
                        *arg = Self::fold_concat_chain_to_transient_calls(owned);
                    }
                }
            }
            HirExpression::Index { array, index, .. } => {
                // `list[idx + "x"]` — the index value is consumed by the
                // subscript operation; same lifetime guarantee as a
                // function-call argument.
                Self::rewrite_call_arg_concats_in_expression(array);
                Self::rewrite_call_arg_concats_in_expression(index);
                if Self::is_provably_string_concat_chain(index) {
                    let owned =
                        std::mem::replace(index.as_mut(), Self::placeholder_void_expression());
                    *index.as_mut() = Self::fold_concat_chain_to_transient_calls(owned);
                }
            }
            HirExpression::Array { elements, .. } => {
                // Array literal elements are NOT consumed-then-discarded
                // — they live as long as the array does. Only descend to
                // find nested call-arg concats; do NOT rewrite the
                // element itself even if it is a concat chain.
                for elem in elements.iter_mut() {
                    Self::rewrite_call_arg_concats_in_expression(elem);
                }
            }
            HirExpression::Cast { expression, .. } => {
                Self::rewrite_call_arg_concats_in_expression(expression);
            }
            HirExpression::BinaryOp { left, right, .. } => {
                Self::rewrite_call_arg_concats_in_expression(left);
                Self::rewrite_call_arg_concats_in_expression(right);
            }
            HirExpression::UnaryOp { operand, .. } => {
                Self::rewrite_call_arg_concats_in_expression(operand);
            }
            HirExpression::FieldAccess { object, .. } => {
                Self::rewrite_call_arg_concats_in_expression(object);
            }
            // Leaves: Literal, Variable, etc. — nothing to rewrite.
            _ => {}
        }
    }

    /// Is this expression a (possibly chained) `BinaryOp::Add` /
    /// `StringConcat`? Used as the predicate for transient-routing the
    /// RHS of a body-local string-typed assignment.
    ///
    /// NOTE: This predicate is intentionally type-blind because the
    /// Step 3 call sites pre-gate on the LHS being a body-local
    /// `string`, which guarantees the chain is on strings. For
    /// call-arg and method-receiver routing (Step 3.5), use
    /// `is_provably_string_concat_chain` — at those sites we have NO
    /// type information about the operands and must conservatively
    /// avoid rewriting integer addition into a string concat call,
    /// which would produce SEM001 "Cannot unify types: integer and
    /// string" errors at typecheck time.
    fn is_string_concat_chain(expr: &HirExpression) -> bool {
        matches!(
            expr,
            HirExpression::BinaryOp {
                op: HirBinaryOp::Add | HirBinaryOp::StringConcat,
                ..
            }
        )
    }

    /// Stricter version of `is_string_concat_chain` for use at call-arg
    /// and method-receiver sites where we have no surrounding type
    /// information.
    ///
    /// A chain qualifies as "provably string concat" only if at least
    /// one leaf operand is a string literal. The Step 3.5 production
    /// shapes all satisfy this:
    ///   - `idx + ".preamble"` — leaf `".preamble"` is a string literal
    ///   - `"[" + idx + "]"` — leaves `"["` and `"]"` are literals
    ///   - `"<h2>" + head + "</h2>"` — multiple literal leaves
    ///
    /// Integer chains like `i + 1`, `count + offset`, or chains where
    /// every leaf is a Variable / Call / Index / FieldAccess are
    /// rejected. The leaves COULD be string-typed at runtime, but
    /// without explicit type information we cannot know — and
    /// rewriting an integer Add into `string_concat_transient` (whose
    /// signature is `(string, string) -> string`) produces a
    /// typecheck failure.
    ///
    /// False negatives (provably string but predicate says no) are
    /// fine: those concats just stay on the main heap, same as
    /// pre-Step-3.5 behavior. False positives (predicate says yes but
    /// chain is integer) would be CORRECTNESS bugs producing SEM001 —
    /// must be impossible.
    fn is_provably_string_concat_chain(expr: &HirExpression) -> bool {
        if !Self::is_string_concat_chain(expr) {
            return false;
        }
        Self::chain_contains_string_literal_leaf(expr)
    }

    /// Walk a `BinaryOp::Add` chain's leaves looking for a string
    /// literal. Returns true if any leaf is a `Literal(String(_))`.
    /// Non-chain expressions are inspected as a single leaf.
    fn chain_contains_string_literal_leaf(expr: &HirExpression) -> bool {
        match expr {
            HirExpression::BinaryOp {
                left,
                op: HirBinaryOp::Add | HirBinaryOp::StringConcat,
                right,
                ..
            } => {
                Self::chain_contains_string_literal_leaf(left)
                    || Self::chain_contains_string_literal_leaf(right)
            }
            HirExpression::Literal {
                value: Value::String(_),
                ..
            } => true,
            _ => false,
        }
    }

    /// Left-fold a `BinaryOp::Add` chain into a sequence of
    /// `Call { function: "string_concat_transient" }` expressions.
    ///
    /// Input: `((a + b) + c) + d` (left-folded `BinaryOp::Add` shape)
    /// Output: `concat(concat(concat(a, b), c), d)` (left-folded Calls)
    ///
    /// Non-chain inputs are returned unchanged.
    fn fold_concat_chain_to_transient_calls(expr: HirExpression) -> HirExpression {
        match expr {
            HirExpression::BinaryOp {
                left,
                op: HirBinaryOp::Add | HirBinaryOp::StringConcat,
                right,
                location,
            } => {
                let folded_left = Self::fold_concat_chain_to_transient_calls(*left);
                let folded_right = *right;
                HirExpression::Call {
                    function: "string_concat_transient".to_string(),
                    arguments: vec![folded_left, folded_right],
                    location,
                }
            }
            other => other,
        }
    }

    /// A void-typed sentinel expression used to satisfy
    /// `mem::replace`'s "need an owned T" requirement when rewriting
    /// in-place. Never reaches the typechecker — the caller immediately
    /// overwrites it with the rewrite output.
    fn placeholder_void_expression() -> HirExpression {
        HirExpression::Literal {
            value: Value::String(String::new()),
            location: SourceLocation::default(),
        }
    }

    /// Build a `name.setFlags(flags)` method call statement.
    /// Emitted after a list variable declaration when the type has a non-Default behavior.
    fn make_set_behavior_stmt(
        &self,
        name: &str,
        behavior: ListBehavior,
        loc: SourceLocation,
    ) -> HirStatement {
        let flags = behavior.to_flags();
        HirStatement::Expression {
            expression: HirExpression::MethodCall {
                receiver: Box::new(HirExpression::Variable {
                    name: name.to_string(),
                    location: loc.clone(),
                }),
                method: "setFlags".to_string(),
                arguments: vec![HirExpression::Literal {
                    value: Value::Integer(flags as i64),
                    location: loc.clone(),
                }],
                location: loc.clone(),
            },
            location: loc,
        }
    }

    /// Desugar a `validate name:` block into a list of HIR statements.
    fn desugar_validate_declaration(
        &mut self,
        schema: &crate::ast::ValidateBlock,
        loc: &SourceLocation,
    ) -> Result<Vec<HirStatement>, CompilerError> {
        let mut stmts: Vec<HirStatement> = Vec::new();
        let schema_name = schema.name.clone();

        // Helper: emit `schemaName = expr` as a VariableDeclaration (first time) or Assignment.
        // We use VariableDeclaration for the first statement and assignments for subsequent ones.
        // Since HIR doesn't distinguish "first use", we use VariableDeclaration with `is_mutable: true`
        // for the create call and Assignment for all subsequent calls that update the same variable.

        // --- Step 1: validator.createWithName(schema_name) ---
        let create_call = HirExpression::Call {
            function: "validator.createWithName".to_string(),
            arguments: vec![HirExpression::Literal {
                value: Value::String(schema_name.clone()),
                location: loc.clone(),
            }],
            location: loc.clone(),
        };
        stmts.push(HirStatement::VariableDeclaration {
            name: schema_name.clone(),
            var_type: HirType::Integer, // rules pointer is i32
            initializer: Some(create_call),
            is_mutable: true,
            location: loc.clone(),
        });

        // --- Step 2: for each field, emit field + constraint calls ---
        let assign_schema = |expr: HirExpression| -> HirStatement {
            HirStatement::Assignment {
                target: HirLValue::Variable {
                    name: schema_name.clone(),
                    location: loc.clone(),
                },
                value: expr,
                location: loc.clone(),
            }
        };

        for field in &schema.fields {
            // validator.field(schema, "fieldName")
            let field_call = HirExpression::Call {
                function: "validator.field".to_string(),
                arguments: vec![
                    HirExpression::Variable {
                        name: schema_name.clone(),
                        location: loc.clone(),
                    },
                    HirExpression::Literal {
                        value: Value::String(field.name.clone()),
                        location: loc.clone(),
                    },
                ],
                location: loc.clone(),
            };
            stmts.push(assign_schema(field_call));

            // validator.type(schema, "typeName") — set the field's expected type name
            let type_name = match field.field_type {
                crate::ast::ValidateFieldType::String => "string",
                crate::ast::ValidateFieldType::Integer => "integer",
                crate::ast::ValidateFieldType::Number => "number",
                crate::ast::ValidateFieldType::Boolean => "boolean",
            };
            let type_call = HirExpression::Call {
                function: "validator.type".to_string(),
                arguments: vec![
                    HirExpression::Variable {
                        name: schema_name.clone(),
                        location: loc.clone(),
                    },
                    HirExpression::Literal {
                        value: Value::String(type_name.to_string()),
                        location: loc.clone(),
                    },
                ],
                location: loc.clone(),
            };
            stmts.push(assign_schema(type_call));

            // Each constraint
            for constraint in &field.constraints {
                let constraint_call = match constraint {
                    ValidateConstraint::Required => HirExpression::Call {
                        function: "validator.required".to_string(),
                        arguments: vec![
                            HirExpression::Variable {
                                name: schema_name.clone(),
                                location: loc.clone(),
                            },
                            HirExpression::Literal {
                                value: Value::Integer(1),
                                location: loc.clone(),
                            },
                        ],
                        location: loc.clone(),
                    },
                    ValidateConstraint::Trim => HirExpression::Call {
                        function: "validator.trim".to_string(),
                        arguments: vec![HirExpression::Variable {
                            name: schema_name.clone(),
                            location: loc.clone(),
                        }],
                        location: loc.clone(),
                    },
                    ValidateConstraint::Length { min, max } => {
                        // Type check: length constraint arguments must be integer literals.
                        // spec/semantic-rules.md: `length` constraint bounds must be integer.
                        if let Expression::Literal(ref v) = **min {
                            if !matches!(
                                v,
                                Value::Integer(_)
                                    | Value::Integer8(_)
                                    | Value::Integer8u(_)
                                    | Value::Integer16(_)
                                    | Value::Integer16u(_)
                                    | Value::Integer32(_)
                                    | Value::Integer64(_)
                            ) {
                                return Err(CompilerError::validation_error(
                                    format!(
                                        "validate length constraint: min argument must be integer, found {}",
                                        v
                                    ),
                                    loc.clone(),
                                ));
                            }
                        }
                        if let Expression::Literal(ref v) = **max {
                            if !matches!(
                                v,
                                Value::Integer(_)
                                    | Value::Integer8(_)
                                    | Value::Integer8u(_)
                                    | Value::Integer16(_)
                                    | Value::Integer16u(_)
                                    | Value::Integer32(_)
                                    | Value::Integer64(_)
                            ) {
                                return Err(CompilerError::validation_error(
                                    format!(
                                        "validate length constraint: max argument must be integer, found {}",
                                        v
                                    ),
                                    loc.clone(),
                                ));
                            }
                        }
                        // Emit minLength and maxLength as two separate calls.
                        let min_hir = self.build_expression(min)?;
                        let max_hir = self.build_expression(max)?;
                        // First emit minLength
                        let min_call = HirExpression::Call {
                            function: "validator.minLength".to_string(),
                            arguments: vec![
                                HirExpression::Variable {
                                    name: schema_name.clone(),
                                    location: loc.clone(),
                                },
                                min_hir,
                            ],
                            location: loc.clone(),
                        };
                        stmts.push(assign_schema(min_call));
                        // Then emit maxLength (we'll emit via the regular path below)
                        HirExpression::Call {
                            function: "validator.maxLength".to_string(),
                            arguments: vec![
                                HirExpression::Variable {
                                    name: schema_name.clone(),
                                    location: loc.clone(),
                                },
                                max_hir,
                            ],
                            location: loc.clone(),
                        }
                    }
                    ValidateConstraint::Min(expr) => {
                        // Type check: min constraint argument must be number or integer.
                        // spec/semantic-rules.md: `min` constraint value must be numeric.
                        if let Expression::Literal(ref v) = **expr {
                            if !matches!(
                                v,
                                Value::Integer(_)
                                    | Value::Integer8(_)
                                    | Value::Integer8u(_)
                                    | Value::Integer16(_)
                                    | Value::Integer16u(_)
                                    | Value::Integer32(_)
                                    | Value::Integer64(_)
                                    | Value::Number(_)
                                    | Value::Number32(_)
                                    | Value::Number64(_)
                            ) {
                                return Err(CompilerError::validation_error(
                                    format!(
                                        "validate min constraint: argument must be number or integer, found {}",
                                        v
                                    ),
                                    loc.clone(),
                                ));
                            }
                        }
                        let hir_expr = self.build_expression(expr)?;
                        HirExpression::Call {
                            function: "validator.range".to_string(),
                            arguments: vec![
                                HirExpression::Variable {
                                    name: schema_name.clone(),
                                    location: loc.clone(),
                                },
                                hir_expr,
                                HirExpression::Literal {
                                    value: Value::Integer(i64::MAX),
                                    location: loc.clone(),
                                },
                            ],
                            location: loc.clone(),
                        }
                    }
                    ValidateConstraint::Max(expr) => {
                        // Type check: max constraint argument must be number or integer.
                        // spec/semantic-rules.md: `max` constraint value must be numeric.
                        if let Expression::Literal(ref v) = **expr {
                            if !matches!(
                                v,
                                Value::Integer(_)
                                    | Value::Integer8(_)
                                    | Value::Integer8u(_)
                                    | Value::Integer16(_)
                                    | Value::Integer16u(_)
                                    | Value::Integer32(_)
                                    | Value::Integer64(_)
                                    | Value::Number(_)
                                    | Value::Number32(_)
                                    | Value::Number64(_)
                            ) {
                                return Err(CompilerError::validation_error(
                                    format!(
                                        "validate max constraint: argument must be number or integer, found {}",
                                        v
                                    ),
                                    loc.clone(),
                                ));
                            }
                        }
                        let hir_expr = self.build_expression(expr)?;
                        HirExpression::Call {
                            function: "validator.range".to_string(),
                            arguments: vec![
                                HirExpression::Variable {
                                    name: schema_name.clone(),
                                    location: loc.clone(),
                                },
                                HirExpression::Literal {
                                    value: Value::Integer(i64::MIN),
                                    location: loc.clone(),
                                },
                                hir_expr,
                            ],
                            location: loc.clone(),
                        }
                    }
                    ValidateConstraint::Match(pattern) => {
                        // SEM010 (validate context): match constraint argument must be a
                        // known pattern name literal.
                        // spec/semantic-rules.md §SEM010
                        const VALID_PATTERNS: &[&str] = &[
                            "email",
                            "url",
                            "uuid",
                            "phone",
                            "date",
                            "integer",
                            "number",
                            "alphanumeric",
                        ];
                        if !VALID_PATTERNS.contains(&pattern.as_str()) {
                            return Err(CompilerError::validation_error(
                                format!(
                                    "Unknown pattern name '{}' in validate match constraint. Valid patterns: email, url, uuid, phone, date, integer, number, alphanumeric",
                                    pattern
                                ),
                                loc.clone(),
                            ));
                        }
                        HirExpression::Call {
                            function: "validator.match".to_string(),
                            arguments: vec![
                                HirExpression::Variable {
                                    name: schema_name.clone(),
                                    location: loc.clone(),
                                },
                                HirExpression::Literal {
                                    value: Value::String(pattern.clone()),
                                    location: loc.clone(),
                                },
                            ],
                            location: loc.clone(),
                        }
                    }
                    ValidateConstraint::OneOf(values) => {
                        // Build a list literal expression containing the oneOf values
                        let hir_values: Result<Vec<HirExpression>, CompilerError> =
                            values.iter().map(|v| self.build_expression(v)).collect();
                        let hir_values = hir_values?;
                        let list_expr = HirExpression::Array {
                            elements: hir_values,
                            element_type: HirType::String, // oneOf values are strings or integers; treat as Any
                            location: loc.clone(),
                        };
                        HirExpression::Call {
                            function: "validator.allowedValues".to_string(),
                            arguments: vec![
                                HirExpression::Variable {
                                    name: schema_name.clone(),
                                    location: loc.clone(),
                                },
                                list_expr,
                            ],
                            location: loc.clone(),
                        }
                    }
                    ValidateConstraint::Custom(fn_name) => HirExpression::Call {
                        function: "validator.custom".to_string(),
                        arguments: vec![
                            HirExpression::Variable {
                                name: schema_name.clone(),
                                location: loc.clone(),
                            },
                            HirExpression::Variable {
                                name: fn_name.clone(),
                                location: loc.clone(),
                            },
                        ],
                        location: loc.clone(),
                    },
                };
                stmts.push(assign_schema(constraint_call));
            }
        }

        // --- Step 3: messages ---
        if let Some(messages) = &schema.messages {
            // Emit per-field message overrides first
            for (field_name, msg_text) in &messages.field_messages {
                // To set a per-field message we need to:
                // 1. Re-select the field: validator.field(schema, fieldName) updates the "current field" pointer
                // 2. Call validator.message(schema, "text")
                let re_field_call = HirExpression::Call {
                    function: "validator.field".to_string(),
                    arguments: vec![
                        HirExpression::Variable {
                            name: schema_name.clone(),
                            location: loc.clone(),
                        },
                        HirExpression::Literal {
                            value: Value::String(field_name.clone()),
                            location: loc.clone(),
                        },
                    ],
                    location: loc.clone(),
                };
                stmts.push(assign_schema(re_field_call));

                let msg_call = HirExpression::Call {
                    function: "validator.message".to_string(),
                    arguments: vec![
                        HirExpression::Variable {
                            name: schema_name.clone(),
                            location: loc.clone(),
                        },
                        HirExpression::Literal {
                            value: Value::String(msg_text.clone()),
                            location: loc.clone(),
                        },
                    ],
                    location: loc.clone(),
                };
                stmts.push(assign_schema(msg_call));
            }

            // Emit default message if present.
            // `validator.message` on the schema level (without a preceding `validator.field`)
            // is treated as the default. We use `validator.createWithName` already set the name,
            // so we call `validator.message` with a special "default" field sentinel handled
            // by the runtime, or we use `validator.field("__default__")` + `validator.message`.
            // The validator runtime's `message` call applies the message to the *last active field*
            // in the current call chain. There is no dedicated "set default" call in the runtime.
            // We emit `validator.field(schema, "__default__") + validator.message(schema, text)`
            // and the runtime silently ignores the unknown "__default__" field name when setting
            // the message, storing it as the schema-level default.
            // Alternatively, we add a dedicated `validator.defaultMessage` call.
            // Looking at the runtime more carefully (generate_validator_message):
            // the runtime stores message per-field in the field_entry. For a true default we
            // need to store it separately. We'll use the approach of adding a field entry named
            // "" (empty string) which the runtime won't find for any real field, and rely on
            // the runtime's fallback logic.
            // The simplest correct approach: just call validator.message with the schema ptr
            // directly — the last field in the schema will receive it. Instead, we emit
            // a dedicated "default" message by calling validator.field("") then validator.message.
            if let Some(default_msg) = &messages.default_message {
                // Use an empty field name as sentinel for the default message.
                // The validator runtime stores this per-field; if none of the real fields
                // have a message set, the runtime returns this as the fallback.
                let default_field_call = HirExpression::Call {
                    function: "validator.field".to_string(),
                    arguments: vec![
                        HirExpression::Variable {
                            name: schema_name.clone(),
                            location: loc.clone(),
                        },
                        HirExpression::Literal {
                            value: Value::String(String::new()),
                            location: loc.clone(),
                        },
                    ],
                    location: loc.clone(),
                };
                stmts.push(assign_schema(default_field_call));

                let default_msg_call = HirExpression::Call {
                    function: "validator.message".to_string(),
                    arguments: vec![
                        HirExpression::Variable {
                            name: schema_name.clone(),
                            location: loc.clone(),
                        },
                        HirExpression::Literal {
                            value: Value::String(default_msg.clone()),
                            location: loc.clone(),
                        },
                    ],
                    location: loc.clone(),
                };
                stmts.push(assign_schema(default_msg_call));
            }
        }

        Ok(stmts)
    }

    /// Desugar a `schemaName.check expr:` block into a list of HIR statements.
    fn desugar_validate_check(
        &mut self,
        check: &crate::ast::ValidateCheckBlock,
        loc: &SourceLocation,
    ) -> Result<Vec<HirStatement>, CompilerError> {
        let schema_name = &check.schema_name;

        // Internal temporary name for the ValidationResult pointer.
        // Use a mangled name to avoid shadowing user variables.
        let result_var = format!("__validate_result_{}__", schema_name);

        // 1. __validate_result_foo__ = validator.run(foo, inputExpr)
        let input_hir = self.build_expression(&check.input)?;
        let run_call = HirExpression::Call {
            function: "validator.run".to_string(),
            arguments: vec![
                HirExpression::Variable {
                    name: schema_name.clone(),
                    location: loc.clone(),
                },
                input_hir,
            ],
            location: loc.clone(),
        };
        let result_decl = HirStatement::VariableDeclaration {
            name: result_var.clone(),
            var_type: HirType::Integer, // ValidationResult pointer is i32
            initializer: Some(run_call),
            is_mutable: false,
            location: loc.clone(),
        };

        // 2. if validator.isOk(__validate_result_foo__):
        //        value = validator.getValue(__validate_result_foo__)
        //        <ok_branch>
        //    else:
        //        errors = validator.getErrors(__validate_result_foo__)
        //        <error_branch>

        // is_ok condition
        let is_ok_cond = HirExpression::Call {
            function: "validator.isOk".to_string(),
            arguments: vec![HirExpression::Variable {
                name: result_var.clone(),
                location: loc.clone(),
            }],
            location: loc.clone(),
        };

        // ok branch: bind `value` then run ok statements
        let get_value_call = HirExpression::Call {
            function: "validator.getValue".to_string(),
            arguments: vec![HirExpression::Variable {
                name: result_var.clone(),
                location: loc.clone(),
            }],
            location: loc.clone(),
        };
        let value_decl = HirStatement::VariableDeclaration {
            name: "value".to_string(),
            var_type: HirType::Any,
            initializer: Some(get_value_call),
            is_mutable: false,
            location: loc.clone(),
        };
        let mut ok_hir_stmts = vec![value_decl];
        for stmt in &check.ok_branch {
            ok_hir_stmts.push(self.build_statement(stmt)?);
        }
        let ok_block = HirBlock {
            statements: ok_hir_stmts,
            location: loc.clone(),
        };

        // error branch: bind `errors` then run error statements
        let get_errors_call = HirExpression::Call {
            function: "validator.getErrors".to_string(),
            arguments: vec![HirExpression::Variable {
                name: result_var.clone(),
                location: loc.clone(),
            }],
            location: loc.clone(),
        };
        let errors_decl = HirStatement::VariableDeclaration {
            name: "errors".to_string(),
            var_type: HirType::List(Box::new(HirType::String)),
            initializer: Some(get_errors_call),
            is_mutable: false,
            location: loc.clone(),
        };
        let mut error_hir_stmts = vec![errors_decl];
        for stmt in &check.error_branch {
            error_hir_stmts.push(self.build_statement(stmt)?);
        }
        let error_block = HirBlock {
            statements: error_hir_stmts,
            location: loc.clone(),
        };

        let if_stmt = HirStatement::If {
            condition: is_ok_cond,
            then_branch: ok_block,
            else_branch: Some(error_block),
            location: loc.clone(),
        };

        Ok(vec![result_decl, if_stmt])
    }
}

